"""Metadata recorded when a response is stored in the cache.

The HTTP ``Date`` header describes when a response was generated by the
origin (or a proxy), not when this client received it.  Proxies can have
clocks that run ahead of the local clock, which makes calculations based on
``Date`` alone under-estimate a response's true age.  The metadata in this
module anchors freshness to the local time at which the response was
received, so that a fast upstream clock (or a local clock that moves
backwards) can never extend how long a cached response is reused.
"""

from __future__ import annotations

import calendar
import time
from dataclasses import dataclass
from email.utils import parsedate_tz
from typing import TYPE_CHECKING, Any, Mapping

if TYPE_CHECKING:
    from urllib3 import HTTPResponse


def parse_age(value: str | None) -> int | None:
    """Parse an ``Age`` header value, returning ``None`` when it is invalid."""
    if value is None:
        return None
    try:
        age = int(value.strip())
    except (TypeError, ValueError):
        return None
    if age < 0:
        return None
    return age


def parse_http_date(value: str | None) -> int | None:
    """Parse an HTTP date into seconds since the epoch."""
    if value is None:
        return None
    time_tuple = parsedate_tz(value)
    if time_tuple is None:
        return None
    return calendar.timegm(time_tuple[:6])


@dataclass(frozen=True)
class CacheMetadata:
    """Local bookkeeping for a response stored in the cache.

    ``response_time`` is the local wall-clock time at which the response was
    received.  ``corrected_initial_age`` is the response's age at that moment,
    derived from ``Date`` and ``Age`` as described by RFC 9111 section 4.2.3.
    ``date`` and ``age`` keep the parsed header values so that callers can
    still observe what the upstream server reported.

    Instances are attached to cached responses as ``response.cache_metadata``
    and persisted by :class:`cachecontrol.serialize.Serializer`.
    """

    response_time: float
    corrected_initial_age: float = 0.0
    monotonic_time: float | None = None
    date: int | None = None
    age: int | None = None

    @classmethod
    def from_response(
        cls,
        response_time: float,
        headers: Mapping[str, str],
        monotonic_time: float | None = None,
    ) -> CacheMetadata:
        """Record the receive time and compute the response's initial age.

        A ``Date`` in the future contributes no age on its own.  Freshness is
        anchored to ``response_time`` instead, so the skewed ``Date`` cannot
        make the response reusable for longer than its declared lifetime.
        """
        date_value = parse_http_date(headers.get("date"))
        age_value = parse_age(headers.get("age"))

        apparent_age = 0.0
        if date_value is not None:
            apparent_age = max(0.0, float(response_time) - date_value)

        # An Age header reflects time spent in upstream caches.  It may only
        # increase the age of the response, never reduce it.
        corrected_initial_age = max(apparent_age, float(age_value or 0))

        return cls(
            response_time=float(response_time),
            corrected_initial_age=corrected_initial_age,
            monotonic_time=(None if monotonic_time is None else float(monotonic_time)),
            date=date_value,
            age=age_value,
        )

    def current_age(
        self, now: float, monotonic_now: float | None = None
    ) -> float | None:
        """Return the response's current age, or ``None`` if it is unusable.

        ``None`` means the local wall clock is now earlier than the recorded
        response time.  Reusing the entry in that situation could postpone
        its expiration, so callers must treat it as stale.

        When a monotonic reading is available, the larger of the two elapsed
        times wins.  A wall-clock rollback therefore cannot reduce the age
        that was already observed.
        """
        elapsed = now - self.response_time
        if elapsed < 0:
            return None

        if self.monotonic_time is not None and monotonic_now is not None:
            monotonic_elapsed = monotonic_now - self.monotonic_time
            # A negative value means the stored reading cannot be compared
            # with this process's monotonic clock (e.g. an entry persisted by
            # another process); fall back to the wall clock in that case.
            if monotonic_elapsed >= 0:
                elapsed = max(elapsed, monotonic_elapsed)

        return self.corrected_initial_age + elapsed

    def to_dict(self) -> dict[str, Any]:
        return {
            "response_time": self.response_time,
            "corrected_initial_age": self.corrected_initial_age,
            "monotonic_time": self.monotonic_time,
            "date": self.date,
            "age": self.age,
        }

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> CacheMetadata | None:
        """Rebuild metadata from a serialized cache entry.

        Unknown or malformed values are ignored so that cache entries written
        by newer versions cannot crash an older reader.
        """
        try:
            response_time = float(data["response_time"])
            corrected_initial_age = float(data.get("corrected_initial_age", 0.0))
        except (KeyError, TypeError, ValueError):
            return None

        monotonic_time = data.get("monotonic_time")
        if monotonic_time is not None:
            try:
                monotonic_time = float(monotonic_time)
            except (TypeError, ValueError):
                monotonic_time = None

        date_value = data.get("date")
        if date_value is not None:
            try:
                date_value = int(date_value)
            except (TypeError, ValueError):
                date_value = None

        age_value = data.get("age")
        if age_value is not None:
            try:
                age_value = int(age_value)
            except (TypeError, ValueError):
                age_value = None

        return cls(
            response_time=response_time,
            corrected_initial_age=max(0.0, corrected_initial_age),
            monotonic_time=monotonic_time,
            date=date_value,
            age=age_value,
        )


def ensure_metadata(
    response: HTTPResponse,
    response_time: float | None = None,
    monotonic_time: float | None = None,
) -> CacheMetadata:
    """Attach local freshness metadata to ``response`` if it has none.

    Returns the metadata now associated with the response.  Existing
    metadata is preserved: when a response is moved from the adapter to the
    cache writer, the arrival time recorded earlier wins over the time the
    body finished downloading.
    """
    metadata = getattr(response, "cache_metadata", None)
    if isinstance(metadata, CacheMetadata):
        return metadata

    if response_time is None:
        response_time = time.time()
    if monotonic_time is None:
        monotonic_time = time.monotonic()
    metadata = CacheMetadata.from_response(
        response_time, response.headers, monotonic_time
    )
    setattr(response, "cache_metadata", metadata)
    return metadata


def response_metadata(response: HTTPResponse) -> CacheMetadata | None:
    """Return the metadata attached to ``response``, if any."""
    metadata = getattr(response, "cache_metadata", None)
    return metadata if isinstance(metadata, CacheMetadata) else None

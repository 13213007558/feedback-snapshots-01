class BadTime(dns.exception.DNSException):
    """The current time is not within the TSIG's validity time.

    This is a local validation result: the MAC was verified, but the
    response's Time Signed is outside the local clock's fudge window.
    """

    authenticated: bool = False
    evidence: "TSIGErrorInfo | None" = None


class BadSignature(dns.exception.DNSException):
    """The TSIG signature fails to verify.

    ``evidence``, when present, describes the TSIG error response whose MAC
    was missing or did not verify.  None of its error fields are trusted.
    """

    authenticated: bool = False
    evidence: "TSIGErrorInfo | None" = None


class BadKey(dns.exception.DNSException):
    """The TSIG record owner name does not match the key."""


class BadAlgorithm(dns.exception.DNSException):
    """The TSIG algorithm does not match the key."""


@dataclasses.dataclass(frozen=True)
class TSIGErrorInfo:
    """Information about a TSIG error response.

    This object deliberately contains no key material.  It is safe to log
    or include in an exception, with the caveat that ``key_name`` and
    ``algorithm`` come from the response and are only meaningful after they
    have been matched against the local key.

    ``authenticated`` is true only when the response's MAC was verified with
    the local key and the response's request MAC.  BADSIG, BADKEY, and
    BADTRUNC responses normally carry an empty MAC, in which case
    ``authenticated`` is false; a non-empty MAC that verifies is still
    reported as authenticated.  A caller must not use any field other than
    the exception class until ``authenticated`` and ``request_mac_bound`` are
    both true.
    """

    error: int
    authenticated: bool
    mac_verified: bool
    request_mac_bound: bool
    request_mac_fingerprint: bytes
    key_name: dns.name.Name | None
    algorithm: dns.name.Name | None
    original_id: int
    time_signed: int
    fudge: int
    server_time: int | None
    time_source: str | None
    other: bytes
    local_time: int
    reason: str

    @property
    def clock_offset(self) -> int | None:
        """The authenticated server time minus the local time, if known.

        This is only a hint for signing a retry.  It is not a command to
        change the system clock, and it must not be used when
        ``authenticated`` or ``request_mac_bound`` is false.
        """
        if self.server_time is None or not self.authenticated:
            return None
        if not self.request_mac_bound:
            return None
        return self.server_time - self.local_time


class PeerError(dns.exception.DNSException):
    """Base class for all TSIG errors generated by the remote peer.

    ``authenticated`` is true only if the MAC of the error response was
    verified.  ``evidence`` contains the verified TSIG error fields, or
    ``None`` if the exception was not created by :func:`validate`.
    """

    authenticated: bool = False
    evidence: "TSIGErrorInfo | None" = None

    def __init__(self, *args, evidence: "TSIGErrorInfo | None" = None):
        super().__init__(*args)
        if evidence is not None:
            self.authenticated = evidence.authenticated
            self.evidence = evidence


class PeerBadKey(PeerError):
    """The peer didn't know the key we used"""


class PeerBadSignature(PeerError):
    """The peer didn't like the signature we sent"""


class PeerBadTime(PeerError):
    """The peer didn't like the time we sent.

    If :attr:`authenticated` is true, :attr:`server_time` is the server's
    time as covered by the verified MAC.  Otherwise it is ``None`` and must
    not be used to adjust a clock or a signing time.
    """

    @property
    def server_time(self) -> int | None:
        """The authenticated server time, or ``None`` if unauthenticated."""
        if self.evidence is None or not self.authenticated:
            return None
        if not self.evidence.request_mac_bound:
            return None
        return self.evidence.server_time


class PeerBadTruncation(PeerError):
    """The peer didn't like amount of truncation in the TSIG we sent"""


class TSIGResponseStatus(enum.Enum):
    """The result of checking a TSIG-signed response against its request."""

    OK = "ok"
    LOCAL_BAD_TIME = "local_bad_time"
    PEER_BAD_TIME = "peer_bad_time"
    PEER_ERROR = "peer_error"
    MISSING_TSIG = "missing_tsig"
    BAD_SIGNATURE = "bad_signature"
    BAD_KEY = "bad_key"
    BAD_ALGORITHM = "bad_algorithm"
    WRONG_TRANSACTION = "wrong_transaction"
    NO_REQUEST_BINDING = "no_request_binding"
    MALFORMED = "malformed"


class TSIGRetryAction(enum.Enum):
    """What a client may do after a TSIG response assessment."""

    NONE = "none"
    RETRY_WITH_TIME_OFFSET = "retry_with_time_offset"
    CHECK_LOCAL_CLOCK = "check_local_clock"


@dataclasses.dataclass(frozen=True)
class TSIGResponseAssessment:
    """A non-raising assessment of a TSIG-signed response.

    All fields except ``detail`` are structured.  ``server_time`` is set only
    when the response MAC verified and the server supplied the time in TSIG
    Other Data; it is never taken from an unauthenticated response.
    """

    status: TSIGResponseStatus
    authenticated: bool
    request_mac_bound: bool
    error: int | None
    rcode: int | None
    key_name: dns.name.Name | None
    algorithm: dns.name.Name | None
    original_id: int | None
    time_signed: int | None
    fudge: int | None
    server_time: int | None
    time_source: str | None
    local_time: int
    transaction_bound: bool
    detail: str

    @property
    def clock_offset(self) -> int | None:
        """The authenticated server time minus the local time, if known."""
        if self.server_time is None or not self.authenticated:
            return None
        if not self.request_mac_bound or not self.transaction_bound:
            return None
        return self.server_time - self.local_time


@dataclasses.dataclass(frozen=True)
class TSIGRetryDecision:
    """A policy decision for a TSIG response.

    ``signing_time_offset`` is added to the local time when signing the next
    request.  It does not change the system clock and it does not change the
    TSIG fudge value.
    """

    action: TSIGRetryAction
    signing_time_offset: int | None
    reason: str


def _server_time(rdata) -> tuple[int | None, str | None]:
    """Return (server time, source) from a BADTIME TSIG rdata.

    RFC 8945 carries the server's current time in Other Data as an unsigned
    48-bit integer.  An empty Other Data is tolerated for compatibility, but
    then there is no server time from which a retry offset may be derived.
    """
    if len(rdata.other) == 6:
        return int.from_bytes(rdata.other, "big"), "other"
    if len(rdata.other) == 0:
        return None, None
    return None, "other-malformed"


def _make_error_info(
    rdata,
    owner: dns.name.Name,
    request_mac: bytes,
    authenticated: bool,
    reason: str,
    local_time: int,
) -> TSIGErrorInfo:
    server_time, time_source = (None, None)
    if authenticated and rdata.error == dns.rcode.BADTIME:
        server_time, time_source = _server_time(rdata)
    elif authenticated and rdata.error == 0:
        # A correctly signed response whose Time Signed is outside the local
        # window still carries an authenticated server time in Time Signed.
        server_time, time_source = rdata.time_signed, "time_signed"
    return TSIGErrorInfo(
        error=int(rdata.error),
        authenticated=authenticated,
        mac_verified=authenticated,
        request_mac_bound=authenticated and bool(request_mac),
        request_mac_fingerprint=hashlib.sha256(request_mac).digest(),
        key_name=owner,
        algorithm=rdata.algorithm,
        original_id=rdata.original_id,
        time_signed=rdata.time_signed,
        fudge=rdata.fudge,
        server_time=server_time,
        time_source=time_source,
        other=rdata.other,
        local_time=local_time,
        reason=reason,
    )


def _peer_error(
    rdata,
    owner: dns.name.Name,
    request_mac: bytes,
    authenticated: bool,
    local_time: int,
) -> PeerError:
    if rdata.error == dns.rcode.BADSIG:
        cls: type[PeerError] = PeerBadSignature
        reason = "peer reported BADSIG"
    elif rdata.error == dns.rcode.BADKEY:
        cls = PeerBadKey
        reason = "peer reported BADKEY"
    elif rdata.error == dns.rcode.BADTIME:
        cls = PeerBadTime
        reason = "peer reported BADTIME"
    elif rdata.error == dns.rcode.BADTRUNC:
        cls = PeerBadTruncation
        reason = "peer reported BADTRUNC"
    else:
        cls = PeerError
        reason = f"peer reported unknown TSIG error {int(rdata.error)}"
    if not authenticated:
        reason += " (response MAC is empty or absent, so the error is unauthenticated)"
    info = _make_error_info(
        rdata, owner, request_mac, authenticated, reason, local_time
    )
    return cls(evidence=info)


def _verify_mac(wire, key, rdata, request_mac, tsig_start, ctx=None, multi=False):
    """Verify the MAC of a TSIG rdata and return the digest context.

    *wire* must be the full wire message, including the TSIG record, and
    *tsig_start* must be the offset of the TSIG record's owner name.
    """
    (adcount,) = struct.unpack("!H", wire[10:12])
    if adcount == 0:
        raise dns.exception.FormError
    adcount -= 1
    new_wire = wire[0:10] + struct.pack("!H", adcount) + wire[12:tsig_start]
    ctx = _digest(new_wire, key, rdata, None, request_mac, ctx, multi)
    ctx.verify(rdata.mac)
    return ctx



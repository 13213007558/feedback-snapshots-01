class GSSTSig:
    """
    GSS-TSIG TSIG implementation.  This uses the GSS-API context established
    in the TKEY message handshake to sign messages using GSS-API message
    integrity codes, per the RFC.

    In order to avoid a direct GSSAPI dependency, the keyring holds a ref
    to the GSSAPI object required, rather than the key itself.
    """

    def __init__(self, gssapi_context):
        self.gssapi_context = gssapi_context
        self.data = b""
        self.name = "gss-tsig"

    def update(self, data):
        self.data += data

    def sign(self):
        # defer to the GSSAPI function to sign
        return self.gssapi_context.get_signature(self.data)

    def verify(self, expected):
        try:
            # defer to the GSSAPI function to verify
            return self.gssapi_context.verify_signature(self.data, expected)
        except Exception:
            # note the usage of a bare exception
            raise BadSignature


class GSSTSigAdapter:
    def __init__(self, keyring):
        self.keyring = keyring

    def __call__(self, message, keyname):
        if keyname in self.keyring:
            key = self.keyring[keyname]
            if isinstance(key, Key) and key.algorithm == GSS_TSIG:
                if message:
                    GSSTSigAdapter.parse_tkey_and_step(key, message, keyname)
            return key
        else:
            return None

    @classmethod
    def parse_tkey_and_step(cls, key, message, keyname):
        # if the message is a TKEY type, absorb the key material
        # into the context using step(); this is used to allow the
        # client to complete the GSSAPI negotiation before attempting
        # to verify the signed response to a TKEY message exchange
        try:
            rrset = message.find_rrset(
                message.answer, keyname, dns.rdataclass.ANY, dns.rdatatype.TKEY
            )
            if rrset:
                token = rrset[0].key
                gssapi_context = key.secret
                return gssapi_context.step(token)
        except KeyError:
            pass


class HMACTSig:
    """
    HMAC TSIG implementation.  This uses the HMAC python module to handle the
    sign/verify operations.
    """

    _hashes = {
        HMAC_SHA1: hashlib.sha1,
        HMAC_SHA224: hashlib.sha224,
        HMAC_SHA256: hashlib.sha256,
        HMAC_SHA256_128: (hashlib.sha256, 128),
        HMAC_SHA384: hashlib.sha384,
        HMAC_SHA384_192: (hashlib.sha384, 192),
        HMAC_SHA512: hashlib.sha512,
        HMAC_SHA512_256: (hashlib.sha512, 256),
        HMAC_MD5: hashlib.md5,
    }

    def __init__(self, key, algorithm):
        try:
            hashinfo = self._hashes[algorithm]
        except KeyError:
            raise NotImplementedError(f"TSIG algorithm {algorithm} is not supported")

        # create the HMAC context
        if isinstance(hashinfo, tuple):
            self.hmac_context = hmac.new(key, digestmod=hashinfo[0])
            self.size = hashinfo[1]
        else:
            self.hmac_context = hmac.new(key, digestmod=hashinfo)
            self.size = None
        self.name = self.hmac_context.name
        if self.size:
            self.name += f"-{self.size}"

    def update(self, data):
        return self.hmac_context.update(data)

    def sign(self):
        # defer to the HMAC digest() function for that digestmod
        digest = self.hmac_context.digest()
        if self.size:
            assert isinstance(self.size, int)
            digest = digest[: (self.size // 8)]
        return digest

    def verify(self, expected):
        # re-digest and compare the results
        mac = self.sign()
        if not hmac.compare_digest(mac, expected):
            raise BadSignature


def _digest(wire, key, rdata, time=None, request_mac=None, ctx=None, multi=None):
    """Return a context containing the TSIG rdata for the input parameters
    @rtype: dns.tsig.HMACTSig or dns.tsig.GSSTSig object
    @raises ValueError: I{other_data} is too long
    @raises NotImplementedError: I{algorithm} is not supported
    """

    first = not (ctx and multi)
    if first:
        ctx = get_context(key)
        if request_mac:
            ctx.update(struct.pack("!H", len(request_mac)))
            ctx.update(request_mac)
    assert ctx is not None  # for type checkers
    ctx.update(struct.pack("!H", rdata.original_id))
    ctx.update(wire[2:])
    if first:
        ctx.update(key.name.to_digestable())
        ctx.update(struct.pack("!H", dns.rdataclass.ANY))
        ctx.update(struct.pack("!I", 0))
    if time is None:
        time = rdata.time_signed
    upper_time = (time >> 32) & 0xFFFF
    lower_time = time & 0xFFFFFFFF
    time_encoded = struct.pack("!HIH", upper_time, lower_time, rdata.fudge)
    other_len = len(rdata.other)
    if other_len > 65535:
        raise ValueError("TSIG Other Data is > 65535 bytes")
    if first:
        ctx.update(key.algorithm.to_digestable() + time_encoded)
        ctx.update(struct.pack("!HH", rdata.error, other_len) + rdata.other)
    else:
        ctx.update(time_encoded)
    return ctx


def _maybe_start_digest(key, mac, multi):
    """If this is the first message in a multi-message sequence,
    start a new context.
    @rtype: dns.tsig.HMACTSig or dns.tsig.GSSTSig object
    """
    if multi:
        ctx = get_context(key)
        ctx.update(struct.pack("!H", len(mac)))
        ctx.update(mac)
        return ctx
    else:
        return None


def sign(wire, key, rdata, time=None, request_mac=None, ctx=None, multi=False):
    """Return a (tsig_rdata, mac, ctx) tuple containing the HMAC TSIG rdata
    for the input parameters, the HMAC MAC calculated by applying the
    TSIG signature algorithm, and the TSIG digest context.
    @rtype: (string, dns.tsig.HMACTSig or dns.tsig.GSSTSig object)
    @raises ValueError: I{other_data} is too long
    @raises NotImplementedError: I{algorithm} is not supported
    """

    ctx = _digest(wire, key, rdata, time, request_mac, ctx, multi)
    mac = ctx.sign()
    tsig = rdata.replace(time_signed=time, mac=mac)

    return (tsig, _maybe_start_digest(key, mac, multi))


def validate(
    wire, key, owner, rdata, now, request_mac, tsig_start, ctx=None, multi=False
):
    """Validate the specified TSIG rdata against the other input parameters.

    The error field and all other TSIG fields are only trusted after the MAC
    has been verified.  The order below is significant: fields which are not
    covered by the MAC must never be allowed to produce a security-relevant
    result before the MAC check.

    A response with a non-zero TSIG error and a non-empty MAC is accepted as a
    peer error only if its MAC verifies.  If the MAC does not verify, a
    :py:exc:`BadSignature` is raised instead.  Error responses defined to
    carry an empty MAC, i.e. BADSIG, BADKEY, and BADTRUNC, are reported as
    unauthenticated peer errors; RFC 8945 defines their MAC field as empty,
    so there is nothing to verify.

    :raises FormError: The TSIG is badly formed.
    :raises BadTime: The response MAC verified, but the response's Time
        Signed is outside the local clock's fudge window.
    :raises BadSignature: The TSIG signature did not validate.
    :raises BadKey: The TSIG owner name does not match the key.
    :raises BadAlgorithm: The TSIG algorithm does not match the key.
    :raises PeerError: The peer reported a TSIG error.  Check the exception's
        ``authenticated`` attribute before trusting ``evidence``.
    :rtype: dns.tsig.HMACTSig or dns.tsig.GSSTSig object"""

    (adcount,) = struct.unpack("!H", wire[10:12])
    if adcount == 0:
        raise dns.exception.FormError
    if key.name != owner:
        raise BadKey
    if key.algorithm != rdata.algorithm:
        raise BadAlgorithm
    if rdata.error != 0 and not rdata.mac:
        # BADSIG, BADKEY, and BADTRUNC have an empty MAC by definition.  Any
        # other error, including BADTIME, must carry a MAC; an empty one is
        # an unsigned claim and is treated as a signature failure so that
        # callers cannot mistake it for a peer report.
        if rdata.error in (dns.rcode.BADSIG, dns.rcode.BADKEY, dns.rcode.BADTRUNC):
            raise _peer_error(rdata, owner, request_mac, False, int(now))
        info = _make_error_info(
            rdata,
            owner,
            request_mac,
            False,
            f"TSIG error {int(rdata.error)} response has no MAC",
            int(now),
        )
        signature_error = BadSignature("TSIG error response has no MAC")
        signature_error.evidence = info
        raise signature_error
    ctx = _verify_mac(wire, key, rdata, request_mac, tsig_start, ctx, multi)
    if rdata.error != 0:
        raise _peer_error(rdata, owner, request_mac, True, int(now))
    if abs(rdata.time_signed - now) > rdata.fudge:
        info = _make_error_info(
            rdata,
            owner,
            request_mac,
            True,
            "response MAC verified but Time Signed is outside the local fudge window",
            int(now),
        )
        time_error = BadTime()
        time_error.authenticated = True
        time_error.evidence = info
        raise time_error
    return _maybe_start_digest(key, rdata.mac, multi)


def _peer_status(error: int) -> TSIGResponseStatus:
    if error == dns.rcode.BADTIME:
        return TSIGResponseStatus.PEER_BAD_TIME
    return TSIGResponseStatus.PEER_ERROR


def assess_tsig_response(
    query: Any, response: Any, now: int | None = None
) -> TSIGResponseAssessment:
    """Assess a TSIG-signed response without raising.

    This checks, in order:

    * that *query* is TSIG-signed and *response* matches its id, opcode, and
      question (the transaction binding);
    * that the response has a TSIG with the query's key name and algorithm;
    * that the response was validated with the query's request MAC;
    * that the response MAC verifies with the query's key and request MAC;
    * only then, the response's TSIG error and Time Signed.

    A response whose MAC does not verify is reported as
    :py:attr:`TSIGResponseStatus.BAD_SIGNATURE`, and no field of its TSIG is
    trusted, including a BADTIME error or a server time in Other Data.

    :param query: The TSIG-signed query.
    :param response: The response message.
    :param now: The local time to compare with Time Signed.  Defaults to
        ``int(time.time())``.
    :rtype: TSIGResponseAssessment
    """

    if now is None:
        now = int(time.time())
    local_time = getattr(response, "tsig_time", None) or now
    rdata = None
    if getattr(response, "had_tsig", False):
        rdata = response.tsig[0]

    key_name = getattr(response, "keyname", None)
    algorithm = getattr(response, "keyalgorithm", None)
    original_id = rdata.original_id if rdata is not None else None
    time_signed = rdata.time_signed if rdata is not None else None
    fudge = rdata.fudge if rdata is not None else None
    error = int(rdata.error) if rdata is not None else None

    def result(
        status: TSIGResponseStatus,
        detail: str,
        *,
        authenticated: bool = False,
        request_mac_bound: bool = False,
        transaction_bound: bool = False,
        server_time: int | None = None,
        time_source: str | None = None,
    ) -> TSIGResponseAssessment:
        return TSIGResponseAssessment(
            status=status,
            authenticated=authenticated,
            request_mac_bound=request_mac_bound,
            error=error,
            rcode=getattr(response, "rcode", lambda: None)(),
            key_name=key_name,
            algorithm=algorithm,
            original_id=original_id,
            time_signed=time_signed,
            fudge=fudge,
            server_time=server_time,
            time_source=time_source,
            local_time=local_time,
            transaction_bound=transaction_bound,
            detail=detail,
        )

    if not getattr(query, "had_tsig", False) or query.mac is None:
        return result(TSIGResponseStatus.NO_REQUEST_BINDING, "query is not TSIG-signed")
    if not query.is_response(response):
        return result(
            TSIGResponseStatus.WRONG_TRANSACTION,
            "response does not match the query id, opcode, or question",
        )
    transaction_bound = True
    if not getattr(response, "had_tsig", False) or rdata is None:
        return result(
            TSIGResponseStatus.MISSING_TSIG,
            "response to a TSIG-signed query has no TSIG",
            transaction_bound=transaction_bound,
        )
    if response.keyname != query.keyname:
        return result(
            TSIGResponseStatus.BAD_KEY,
            "response TSIG key name differs from the query's key name",
            transaction_bound=transaction_bound,
        )
    if response.keyalgorithm != query.keyalgorithm:
        return result(
            TSIGResponseStatus.BAD_ALGORITHM,
            "response TSIG algorithm differs from the query's algorithm",
            transaction_bound=transaction_bound,
        )
    if not response.request_mac or not hmac.compare_digest(
        response.request_mac, query.mac
    ):
        return result(
            TSIGResponseStatus.NO_REQUEST_BINDING,
            "response was not validated with this query's request MAC",
            transaction_bound=transaction_bound,
        )
    request_mac_bound = True

    wire = getattr(response, "tsig_wire", None)
    tsig_start = getattr(response, "tsig_start", None)
    if wire is None or tsig_start is None:
        return result(
            TSIGResponseStatus.BAD_SIGNATURE,
            "cannot re-verify the response MAC without its wire format",
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
        )
    if rdata.error != 0 and not rdata.mac:
        # BADKEY, BADSIG, and BADTRUNC are defined to carry an empty MAC, so
        # there is nothing to authenticate.  Report the peer's claim, but do
        # not mark it authenticated and do not trust Other Data.
        if rdata.error in (dns.rcode.BADSIG, dns.rcode.BADKEY, dns.rcode.BADTRUNC):
            return result(
                _peer_status(int(rdata.error)),
                "peer error has an empty MAC; the error is unauthenticated",
                request_mac_bound=request_mac_bound,
                transaction_bound=transaction_bound,
            )
        return result(
            TSIGResponseStatus.BAD_SIGNATURE,
            "TSIG error response has no MAC",
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
        )
    key = query.keyring
    if not isinstance(key, Key):
        return result(
            TSIGResponseStatus.NO_REQUEST_BINDING,
            "query's keyring is not a single Key",
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
        )
    try:
        _verify_mac(wire, key, rdata, query.mac, tsig_start)
    except BadSignature:
        return result(
            TSIGResponseStatus.BAD_SIGNATURE,
            "response MAC does not verify with the query's key and request MAC",
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
        )
    except Exception:
        return result(
            TSIGResponseStatus.MALFORMED,
            "response TSIG could not be verified",
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
        )

    if rdata.error != 0:
        server_time, time_source = (None, None)
        if rdata.error == dns.rcode.BADTIME:
            server_time, time_source = _server_time(rdata)
        return result(
            _peer_status(int(rdata.error)),
            "response MAC verified; the error code and Other Data are authenticated",
            authenticated=True,
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
            server_time=server_time,
            time_source=time_source,
        )
    if abs(rdata.time_signed - now) > rdata.fudge:
        return result(
            TSIGResponseStatus.LOCAL_BAD_TIME,
            "response MAC verified but Time Signed is outside the local fudge window",
            authenticated=True,
            request_mac_bound=request_mac_bound,
            transaction_bound=transaction_bound,
            server_time=rdata.time_signed,
            time_source="time_signed",
        )
    return result(
        TSIGResponseStatus.OK,
        "response MAC and time are valid",
        authenticated=True,
        request_mac_bound=request_mac_bound,
        transaction_bound=transaction_bound,
    )


def assess_tsig_error(
    query: Any, error: Exception, now: int | None = None
) -> TSIGResponseAssessment:
    """Assess an exception raised while validating a TSIG response.

    This is the exception-path counterpart of :func:`assess_tsig_response`.
    A :py:exc:`PeerBadTime` is trusted only when its ``authenticated``
    attribute is true, which requires that the response MAC verified.  A
    :py:exc:`BadTime` is a local validation result and is classified as
    :py:attr:`TSIGResponseStatus.LOCAL_BAD_TIME`.

    Transaction binding is established from the decoded response message
    attached to the exception by :func:`dns.message.from_wire`, if
    available.  Otherwise it falls back to the MAC-covered Original ID plus
    the request MAC binding; use :func:`assess_tsig_response` when the
    question section must also be checked.

    :param query: The TSIG-signed query.
    :param error: The exception raised by ``dns.message.from_wire()``.
    :param now: The local time used for the assessment.
    :rtype: TSIGResponseAssessment
    """

    if now is None:
        now = int(time.time())
    # Imported here because dns.message imports this module.
    import dns.message

    evidence = getattr(error, "evidence", None)
    response = getattr(error, "message", None)
    transaction_bound = False
    if response is not None and query.is_response(response):
        transaction_bound = True
    if evidence is None:
        if isinstance(error, PeerError):
            detail = "peer TSIG error has no authentication evidence"
        elif isinstance(error, BadTime):
            detail = "local BadTime has no authentication evidence"
        elif isinstance(error, BadSignature):
            detail = "response MAC did not verify"
        elif isinstance(error, BadKey):
            detail = "response TSIG key name does not match the local key"
        elif isinstance(error, BadAlgorithm):
            detail = "response TSIG algorithm does not match the local key"
        elif isinstance(error, dns.message.MissingTSIG):
            detail = "response to a TSIG-signed query has no TSIG"
        else:
            detail = "response is not a usable TSIG response"
        status = TSIGResponseStatus.MALFORMED
        if isinstance(error, dns.message.MissingTSIG):
            status = TSIGResponseStatus.MISSING_TSIG
        elif isinstance(error, BadSignature):
            status = TSIGResponseStatus.BAD_SIGNATURE
        elif isinstance(error, BadKey):
            status = TSIGResponseStatus.BAD_KEY
        elif isinstance(error, BadAlgorithm):
            status = TSIGResponseStatus.BAD_ALGORITHM
        elif isinstance(error, BadTime):
            status = TSIGResponseStatus.LOCAL_BAD_TIME
        return TSIGResponseAssessment(
            status=status,
            authenticated=False,
            request_mac_bound=False,
            transaction_bound=transaction_bound,
            error=None,
            rcode=None,
            key_name=query.keyname,
            algorithm=query.keyalgorithm,
            original_id=None,
            time_signed=None,
            fudge=None,
            server_time=None,
            time_source=None,
            local_time=now,
            detail=detail,
        )

    request_mac_bound = bool(
        evidence.authenticated
        and query.mac
        and hmac.compare_digest(
            evidence.request_mac_fingerprint, hashlib.sha256(query.mac).digest()
        )
    )
    key_name_ok = evidence.key_name == query.keyname
    algorithm_ok = evidence.algorithm == query.keyalgorithm
    authenticated = bool(evidence.authenticated and key_name_ok and algorithm_ok)
    transaction_bound = bool(authenticated and request_mac_bound)
    if response is not None:
        transaction_bound = transaction_bound and bool(query.is_response(response))
    else:
        transaction_bound = transaction_bound and evidence.original_id == query.id
    server_time = evidence.server_time if authenticated else None
    time_source = evidence.time_source if authenticated else None

    if isinstance(error, PeerBadTime):
        status = TSIGResponseStatus.PEER_BAD_TIME
    elif isinstance(error, PeerError):
        status = TSIGResponseStatus.PEER_ERROR
    elif isinstance(error, dns.message.MissingTSIG):
        status = TSIGResponseStatus.MISSING_TSIG
    elif isinstance(error, BadTime):
        status = TSIGResponseStatus.LOCAL_BAD_TIME
    elif isinstance(error, BadSignature):
        status = TSIGResponseStatus.BAD_SIGNATURE
    elif isinstance(error, BadKey):
        status = TSIGResponseStatus.BAD_KEY
    elif isinstance(error, BadAlgorithm):
        status = TSIGResponseStatus.BAD_ALGORITHM
    else:
        status = TSIGResponseStatus.MALFORMED

    detail = evidence.reason
    if not key_name_ok:
        detail += "; key name does not match the query"
    if not algorithm_ok:
        detail += "; algorithm does not match the query"
    if not request_mac_bound:
        detail += "; request MAC does not match the query"
    if authenticated and response is None and evidence.original_id != query.id:
        detail += "; original id does not match the query"
    if not transaction_bound:
        detail += "; transaction binding is incomplete"

    return TSIGResponseAssessment(
        status=status,
        authenticated=authenticated,
        request_mac_bound=request_mac_bound,
        transaction_bound=transaction_bound,
        error=evidence.error,
        rcode=None,
        key_name=evidence.key_name,
        algorithm=evidence.algorithm,
        original_id=evidence.original_id,
        time_signed=evidence.time_signed,
        fudge=evidence.fudge,
        server_time=server_time,
        time_source=time_source,
        local_time=evidence.local_time,
        detail=detail,
    )


@dataclasses.dataclass(frozen=True)
class TSIGRetryPolicy:
    """Limits on automatic retries after an authenticated TSIG BADTIME.

    The policy never changes the system clock and never changes the TSIG
    fudge.  A retry signs the next request with a bounded offset from the
    authenticated server time.  Anything outside the policy requires an
    operator to check the local clock.
    """

    #: Maximum number of automatic retries per transaction.
    max_retries: int = 1
    #: Maximum absolute offset, in seconds, that may be applied to a retry.
    max_offset: int = 300


def decide_tsig_retry(
    assessment: TSIGResponseAssessment,
    attempt: int = 0,
    policy: TSIGRetryPolicy | None = None,
) -> TSIGRetryDecision:
    """Decide whether a TSIG response permits an automatic retry.

    Only an authenticated, request-MAC-bound, transaction-bound peer BADTIME
    with a server time within the policy's offset limit may cause a retry.
    A local :py:exc:`BadTime` means the local clock should be checked; it is
    not a license to adopt the server's time.

    :param assessment: The result of :func:`assess_tsig_response` or
        :func:`assess_tsig_error`.
    :param attempt: The number of automatic retries already made.
    :param policy: The retry policy.  Defaults to :py:class:`TSIGRetryPolicy`.
    :rtype: TSIGRetryDecision
    """

    if policy is None:
        policy = TSIGRetryPolicy()
    if assessment.status is TSIGResponseStatus.OK:
        return TSIGRetryDecision(TSIGRetryAction.NONE, None, "response is valid")
    if assessment.status is TSIGResponseStatus.LOCAL_BAD_TIME:
        return TSIGRetryDecision(
            TSIGRetryAction.CHECK_LOCAL_CLOCK,
            None,
            "local time validation failed; check the local clock",
        )
    if assessment.status is TSIGResponseStatus.PEER_BAD_TIME:
        if not assessment.authenticated:
            return TSIGRetryDecision(
                TSIGRetryAction.NONE,
                None,
                "peer BADTIME is not authenticated by a verified MAC",
            )
        if not assessment.request_mac_bound or not assessment.transaction_bound:
            return TSIGRetryDecision(
                TSIGRetryAction.NONE,
                None,
                "authenticated BADTIME is not bound to this request and transaction",
            )
        if assessment.server_time is None:
            return TSIGRetryDecision(
                TSIGRetryAction.CHECK_LOCAL_CLOCK,
                None,
                "authenticated BADTIME did not include a usable server time",
            )
        offset = assessment.clock_offset
        if offset is None or offset == 0:
            return TSIGRetryDecision(
                TSIGRetryAction.CHECK_LOCAL_CLOCK,
                None,
                "authenticated server time does not imply a usable offset",
            )
        if abs(offset) > policy.max_offset:
            return TSIGRetryDecision(
                TSIGRetryAction.CHECK_LOCAL_CLOCK,
                None,
                "authenticated clock offset exceeds the retry policy limit",
            )
        if attempt >= policy.max_retries:
            return TSIGRetryDecision(
                TSIGRetryAction.NONE, None, "automatic retry budget is exhausted"
            )
        return TSIGRetryDecision(
            TSIGRetryAction.RETRY_WITH_TIME_OFFSET,
            offset,
            "authenticated BADTIME permits one bounded signing-time retry",
        )
    return TSIGRetryDecision(
        TSIGRetryAction.NONE, None, "response does not permit an automatic retry"
    )


def get_context(key):
    """Returns an HMAC context for the specified key.

    @rtype: HMAC context
    @raises NotImplementedError: I{algorithm} is not supported
    """

    if key.algorithm == GSS_TSIG:
        return GSSTSig(key.secret)
    else:
        return HMACTSig(key.secret, key.algorithm)


class Key:
    def __init__(
        self,
        name: dns.name.Name | str,
        secret: bytes | str,
        algorithm: dns.name.Name | str = default_algorithm,
    ):
        if isinstance(name, str):
            name = dns.name.from_text(name)
        self.name = name
        if isinstance(secret, str):
            secret = base64.decodebytes(secret.encode())
        self.secret = secret
        if isinstance(algorithm, str):
            algorithm = dns.name.from_text(algorithm)
        self.algorithm = algorithm

    def __eq__(self, other):
        return (
            isinstance(other, Key)
            and self.name == other.name
            and self.secret == other.secret
            and self.algorithm == other.algorithm
        )

    def __repr__(self):
        r = f"<DNS key name='{self.name}', " + f"algorithm='{self.algorithm}'"
        if self.algorithm != GSS_TSIG:
            r += f", secret='{base64.b64encode(self.secret).decode()}'"
        r += ">"
        return r

# coding: utf-8
# frozen_string_literal: false

require "rexml/document"
require "stringio"

module REXMLTests
  # Generative tests for the encoding entry points of REXML.
  #
  # They prove that, when the BOM, the XML text declaration and the IO encoding
  # information disagree (or the byte stream is cut in the middle of a
  # multibyte character / of the XML declaration), REXML never silently drops
  # bytes and never reinterprets one document as another.
  #
  # Expected codepoints are produced by this generator and stored next to each
  # byte stream; they are never reverse engineered from a parser result.
  class EncodingEntryTest < Test::Unit::TestCase
    # Independent reference content, fixed by the generator. It spans 1-, 2-,
    # 3- and 4-byte UTF-8 sequences and a character outside the BMP so that a
    # UTF-16 surrogate pair is exercised too.
    CODEPOINTS = [0x41, 0xE9, 0x20AC, 0x1F600].freeze # A, é, €, 😀
    TEXT = CODEPOINTS.pack("U*").freeze
    ROOT = "r".freeze

    BOM = {
      "UTF-8" => "\xEF\xBB\xBF".b,
      "UTF-16LE" => "\xFF\xFE".b,
      "UTF-16BE" => "\xFE\xFF".b,
    }.freeze

    ENCODINGS = ["UTF-8", "UTF-16LE", "UTF-16BE"].freeze
    SHORT_READ_SIZES = [1, 2, 3, 5, 7, 13].freeze

    # An IO whose underlying store hands over at most +chunk+ bytes at a time,
    # modelling a socket/pipe that returns short reads. It keeps the contract
    # of a real IO:
    #   * read(n) may return fewer than n bytes;
    #   * readline(rs) still honours the record separator;
    #   * bytes are delivered verbatim and only *tagged* with the external
    #     encoding once set_encoding is called, leaving REXML to perform the
    #     actual charset decoding (as it does for a binmode IO).
    class ShortReadIO
      def initialize(bytes, chunk)
        @store = StringIO.new(bytes.b)
        @chunk = chunk
        @buffer = "".b
        @external = Encoding::ASCII_8BIT
      end

      def read(length = nil)
        length ? @store.read(length) : @store.read(@chunk)
      end

      def readline(separator = $/)
        separator = separator.to_s.b
        line = loop do
          index = @buffer.index(separator)
          break @buffer.slice!(0, index + separator.bytesize) if index
          piece = @store.read(@chunk)
          if piece.nil? || piece.empty?
            raise EOFError if @buffer.empty?
            tail = @buffer.dup
            @buffer.clear
            break tail
          end
          @buffer << piece.b
        end
        line.force_encoding(@external)
      end

      def eof?
        @store.eof? && @buffer.empty?
      end

      def binmode
        @store.binmode
        @external = Encoding::ASCII_8BIT
        self
      end

      def set_encoding(external, *arguments)
        @store.set_encoding(external, *arguments)
        @external = external.is_a?(Encoding) ? external : Encoding.find(external.to_s)
      end

      def external_encoding
        @store.external_encoding
      end

      def pos
        @store.pos - @buffer.bytesize
      end

      def lineno
        @store.lineno
      end

      def rewind
        @store.rewind
        @buffer.clear
      end

      def seek(*arguments)
        @store.seek(*arguments)
        @buffer.clear
      end

      def close
        @store.close
      end
    end

    # A generated byte stream plus the codepoints the generator expects back.
    # +recoverable+ says whether the stream is a complete, well-formed
    # document; +split_at+ is set only for boundary-split cases.
    GeneratedCase = Struct.new(:name, :bytes, :codepoints, :recoverable,
                               :split_at, keyword_init: true)

    private

    def valid_bytes(encoding)
      case encoding
      when "UTF-8"
        BOM["UTF-8"] +
          ('<?xml version="1.0"?><r>' + TEXT.encode("UTF-8") + "</r>").b
      when "UTF-16LE", "UTF-16BE"
        BOM[encoding] +
          ('<?xml version="1.0" encoding="UTF-16"?><r>' + TEXT + "</r>").
            encode(encoding).b
      end
    end

    def valid_case(encoding)
      GeneratedCase.new(
        name: "valid #{encoding}",
        bytes: valid_bytes(encoding),
        codepoints: CODEPOINTS.dup,
        recoverable: true,
      )
    end

    # Every prefix length of the encoded text, keeping the well-formed closing
    # tag. Odd byte counts in UTF-16 leave a lone code unit byte and every cut
    # inside a UTF-8 multibyte sequence leaves an incomplete character.
    def truncation_cases(encoding)
      raw = TEXT.encode(encoding).b
      (1...raw.bytesize).map do |cut|
        kept = raw.byteslice(0, raw.bytesize - cut)
        expected = decodable_prefix_codepoints(kept, encoding)
        GeneratedCase.new(
          name: "truncated #{encoding} cut-#{cut}",
          bytes: build_document(encoding, kept),
          codepoints: expected || [],
          recoverable: !expected.nil?,
        )
      end
    end

    # Decode whole characters straight from the bytes, without REXML.
    # Returns nil for an incomplete trailing multibyte sequence.
    def decodable_prefix_codepoints(bytes, encoding)
      tagged = bytes.dup.force_encoding(encoding)
      return nil unless tagged.valid_encoding?
      tagged.encode("UTF-8").codepoints.to_a
    rescue ArgumentError, EncodingError
      nil
    end

    def build_document(encoding, text_bytes)
      case encoding
      when "UTF-8"
        BOM["UTF-8"] + '<?xml version="1.0"?><r>'.b + text_bytes + "</r>".b
      when "UTF-16LE", "UTF-16BE"
        BOM[encoding] +
          '<?xml version="1.0" encoding="UTF-16"?>'.encode(encoding).b +
          "<r>".encode(encoding).b +
          text_bytes +
          "</r>".encode(encoding).b
      end
    end

    # BOM / declaration conflicts. The two sources of encoding information
    # must not be silently reconciled, so every case is expected to be raised.
    def conflict_cases
      [
        conflict("UTF-16LE BOM but declaration says UTF-8",
                 "UTF-16LE", '<?xml version="1.0" encoding="UTF-8"?><r>x</r>'),
        conflict("UTF-16BE BOM but declaration says UTF-8",
                 "UTF-16BE", '<?xml version="1.0" encoding="UTF-8"?><r>x</r>'),
        conflict("UTF-16LE BOM but declaration says UTF-16BE",
                 "UTF-16LE", '<?xml version="1.0" encoding="UTF-16BE"?><r>x</r>'),
        conflict("UTF-16BE BOM but declaration says UTF-16LE",
                 "UTF-16BE", '<?xml version="1.0" encoding="UTF-16LE"?><r>x</r>'),
        bomless_utf16_conflict,
      ]
    end

    # UTF-16 code units without a BOM look like ASCII bytes interleaved with
    # NULs. There is no way to self-detect the encoding, so REXML must reject
    # the stream instead of reading it as a different (NUL-laden) document.
    def bomless_utf16_conflict
      markup = '<?xml version="1.0" encoding="UTF-16"?><r>x</r>'
      GeneratedCase.new(
        name: "UTF-16LE bytes without a BOM",
        bytes: markup.encode("UTF-16LE").b,
        codepoints: [0x78],
        recoverable: false,
      )
    end

    def conflict(name, body_encoding, markup)
      GeneratedCase.new(
        name: name,
        bytes: BOM[body_encoding] + markup.encode(body_encoding).b,
        codepoints: [0x78],
        recoverable: false,
      )
    end

    # The same valid document with its declaration cut at every possible byte
    # boundary, so the declaration always spans at least two reads.
    def boundary_cases(encoding)
      bytes = valid_bytes(encoding)
      (1...bytes.bytesize).map do |cut|
        GeneratedCase.new(
          name: "boundary split #{encoding} at #{cut}",
          bytes: bytes,
          codepoints: CODEPOINTS.dup,
          recoverable: true,
          split_at: cut,
        )
      end
    end

    def parse(input)
      document = REXML::Document.new(input)
      [:ok, document]
    rescue REXML::ParseException => error
      [:raised, error]
    end

    def codepoints_of(document)
      document.root.text.codepoints.to_a
    end

    def assert_recovered(document, test_case)
      assert_not_nil(document.root, "#{test_case.name}: expected a root element")
      assert_equal(ROOT, document.root.name, "#{test_case.name}: root name")
      assert_equal(test_case.codepoints, codepoints_of(document),
                   "#{test_case.name}: codepoints must match the generator")
    end

    def as_string(bytes)
      bytes.dup.force_encoding(Encoding::ASCII_8BIT)
    end

    public

    # --- Valid round trip through every entry shape ------------------------

    ENCODINGS.each do |encoding|
      define_method("test_valid_round_trip_string_#{encoding}") do
        test_case = valid_case(encoding)
        status, document = parse(as_string(test_case.bytes))
        assert_equal(:ok, status, test_case.name)
        assert_recovered(document, test_case)
      end

      define_method("test_valid_round_trip_string_io_#{encoding}") do
        test_case = valid_case(encoding)
        status, document = parse(StringIO.new(test_case.bytes.dup))
        assert_equal(:ok, status, test_case.name)
        assert_recovered(document, test_case)
      end
    end

    # --- Truncated multibyte characters ------------------------------------

    ENCODINGS.each do |encoding|
      define_method("test_truncation_string_#{encoding}") do
        truncation_cases(encoding).each do |test_case|
          status, document = parse(as_string(test_case.bytes))
          if test_case.recoverable
            assert_equal(:ok, status, "#{test_case.name} should parse")
            assert_recovered(document, test_case)
          else
            assert_equal(:raised, status,
                         "#{test_case.name}: incomplete sequence must be rejected")
          end
        end
      end

      define_method("test_truncation_string_and_io_parity_#{encoding}") do
        truncation_cases(encoding).each do |test_case|
          string_status, string_doc = parse(as_string(test_case.bytes))
          io_status, io_doc = parse(StringIO.new(test_case.bytes.dup))
          assert_equal(string_status, io_status,
                       "#{test_case.name}: String and IO must agree")
          if string_status == :ok
            assert_equal(codepoints_of(string_doc), codepoints_of(io_doc),
                         "#{test_case.name}: identical codepoints")
          end
        end
      end
    end

    # --- BOM / declaration conflicts ---------------------------------------

    def test_conflicts_rejected_from_string
      conflict_cases.each do |test_case|
        status, = parse(as_string(test_case.bytes))
        assert_equal(:raised, status,
                     "#{test_case.name}: conflicting metadata must be rejected")
      end
    end

    def test_conflicts_rejected_from_io
      conflict_cases.each do |test_case|
        status, = parse(StringIO.new(test_case.bytes.dup))
        assert_equal(:raised, status,
                     "#{test_case.name}: conflicting metadata must be rejected")
      end
    end

    # A failed parse must never surface a partially built "prefix" document:
    # the only object handed back is the exception, never a Document.
    def test_conflict_failure_leaves_no_prefix_document
      conflict_cases.each do |test_case|
        status, result = parse(as_string(test_case.bytes))
        assert_equal(:raised, status, test_case.name)
        assert_instance_of(REXML::ParseException, result,
                           "#{test_case.name}: failure must not return a document")
      end
    end

    # A pre-existing Document used as the parse target is left untouched when
    # the stream is rejected.
    def test_failure_does_not_mutate_target_document
      target = REXML::Document.new("<existing/>")
      test_case = conflict_cases.first
      assert_raise(REXML::ParseException) do
        REXML::Document.new(as_string(test_case.bytes), target)
      end
      assert_equal("existing", target.root.name)
      assert_equal(1, target.children.size)
    end

    # --- Declaration split across read boundaries --------------------------

    ENCODINGS.each do |encoding|
      define_method("test_declaration_boundary_splits_#{encoding}") do
        boundary_cases(encoding).each do |test_case|
          io = ShortReadIO.new(test_case.bytes.dup, test_case.split_at)
          status, document = parse(io)
          assert_equal(:ok, status,
                       "#{test_case.name}: split declaration must reassemble")
          assert_recovered(document, test_case)
        end
      end
    end

    # --- String vs short-read IO parity ------------------------------------

    ENCODINGS.each do |encoding|
      define_method("test_valid_round_trip_short_read_io_#{encoding}") do
        test_case = valid_case(encoding)
        SHORT_READ_SIZES.each do |chunk|
          status, document = parse(ShortReadIO.new(test_case.bytes.dup, chunk))
          assert_equal(:ok, status,
                       "#{test_case.name} chunk=#{chunk}: must parse")
          assert_recovered(document, test_case)
        end
      end

      define_method("test_string_and_short_read_io_parity_#{encoding}") do
        test_case = valid_case(encoding)
        string_status, string_doc = parse(as_string(test_case.bytes))

        SHORT_READ_SIZES.each do |chunk|
          io_status, io_doc = parse(ShortReadIO.new(test_case.bytes.dup, chunk))
          # A short-read IO must be semantically identical to the String:
          # either both recover the generator codepoints, or both reject.
          assert_equal(string_status, io_status,
                       "#{test_case.name} chunk=#{chunk}: status parity")
          if string_status == :ok
            assert_equal(codepoints_of(string_doc), codepoints_of(io_doc),
                         "#{test_case.name} chunk=#{chunk}: codepoint parity")
          end
        end
      end

      define_method("test_truncation_short_read_io_parity_#{encoding}") do
        truncation_cases(encoding).each do |test_case|
          string_status, string_doc = parse(as_string(test_case.bytes))
          SHORT_READ_SIZES.each do |chunk|
            io_status, io_doc = parse(ShortReadIO.new(test_case.bytes.dup, chunk))
            assert_equal(string_status, io_status,
                         "#{test_case.name} chunk=#{chunk}: status parity")
            if string_status == :ok
              assert_equal(codepoints_of(string_doc), codepoints_of(io_doc),
                           "#{test_case.name} chunk=#{chunk}: codepoint parity")
            end
          end
        end
      end
    end
  end
end

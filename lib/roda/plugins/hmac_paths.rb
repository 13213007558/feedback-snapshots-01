# frozen-string-literal: true

require 'openssl'

#
class Roda
  module RodaPlugins
    # The hmac_paths plugin allows protection of paths using an HMAC.  This can be used
    # to prevent users enumerating paths, since only paths with valid HMACs will be
    # respected.
    #
    # To use the plugin, you must provide a +secret+ argument.  This sets the secret for
    # the HMACs.  Make sure to keep this value secret, as this plugin does not provide
    # protection against users who know the secret value.  The secret must be at least
    # 32 bytes.
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes'
    #
    # To generate a valid HMAC path, you call the +hmac_path+ method:
    #
    #   hmac_path('/widget/1')
    #   # => "/0c2feaefdfc80cc73da19b060c713d4193c57022815238c6657ce2d99b5925eb/0/widget/1"
    #
    # The first segment in the returned path is the HMAC.  The second segment is flags for
    # the type of paths (see below), and the rest of the path is as given.
    #
    # To protect a path or any subsection in the routing tree, you wrap the related code
    # in an +r.hmac_path+ block.
    #
    #   route do |r|
    #     r.hmac_path do
    #       r.get 'widget', Integer do |widget_id|
    #         # ...
    #       end
    #     end
    #   end
    #
    # If first segment of the remaining path contains a valid HMAC for the rest of the path (considering
    # the flags), then +r.hmac_path+ will match and yield to the block, and routing continues inside
    # the block with the HMAC and flags segments removed.
    #
    # In the above example, if you provide a user a link for widget with ID 1, there is no way
    # for them to guess the valid path for the widget with ID 2, preventing a user from
    # enumerating widgets, without relying on custom access control.  Users can only access
    # paths that have been generated by the application and provided to them, either directly
    # or indirectly.
    #
    # In the above example, +r.hmac_path+ is used at the root of the routing tree. If you
    # would like to call it below the root of the routing tree, it works correctly, but you
    # must pass +hmac_path+ the +root+ argument specifying where +r.hmac_paths+ will be called from.
    # Consider this example:
    #
    #   route do |r|
    #     r.on 'widget' do
    #       r.hmac_path do
    #         r.get Integer do |widget_id|
    #           # ...
    #         end
    #       end
    #     end
    #
    #     r.on 'foobar' do
    #       r.hmac_path do
    #         r.get Integer do |foobar_id|
    #           # ...
    #         end
    #       end
    #     end
    #   end
    #
    # For security reasons, the hmac_path plugin does not allow an HMAC path designed for
    # widgets to be a valid match in the +r.hmac_path+ call inside the <tt>r.on 'foobar'</tt>
    # block, preventing users who have a valid HMAC for a widget from looking at the page for
    # a foobar with the same ID.  When generating HMAC paths where the matching +r.hmac_path+
    # call is not at the root of the routing tree, you must pass the +root+ argument:
    #
    #   hmac_path('/1', root: '/widget')
    #   # => "/widget/daccafce3ce0df52e5ce774626779eaa7286085fcbde1e4681c74175ff0bbacd/0/1"
    #
    #   hmac_path('/1', root: '/foobar')
    #   # => "/foobar/c5fdaf482771d4f9f38cc13a1b2832929026a4ceb05e98ed6a0cd5a00bf180b7/0/1"
    #
    # Note how the HMAC changes even though the path is the same.
    #
    # In addition to the +root+ argument, there are additional arguments that further constrain
    # use of the generated paths.
    #
    # The +method+ argument creates a path that can only be called with a certain request
    # method:
    #
    #   hmac_path('/widget/1', method: :get)
    #   # => "/d38c1e634ecf9a3c0ab9d0832555b035d91b35069efcbf2670b0dfefd4b62fdd/m/widget/1"
    #
    # Note how this results in a different HMAC than the original <tt>hmac_path('/widget/1')</tt>
    # call.  This sets the flags segment to +m+, which means +r.hmac_path+ will consider the
    # request mehod when checking the HMAC, and will only match if the provided request method
    # is GET.  This allows you to provide a user the ability to submit a GET request for the
    # underlying path, without providing them the ability to submit a POST request for the
    # underlying path, with no other access control.
    #
    # The +params+ argument accepts a hash of params, converts it into a query string, and
    # includes the query string in the returned path.  It sets the flags segment to +p+, which
    # means +r.hmac_path+ will check for that exact query string.  Requests with an empty query
    # string or a different string will not match.
    #
    #   hmac_path('/widget/1', params: {foo: 'bar'})
    #   # => "/fe8d03f9572d5af6c2866295bd3c12c2ea11d290b1cbd016c3b68ee36a678139/p/widget/1?foo=bar"
    #
    # For GET requests, which cannot have request bodies, that is sufficient to ensure that the
    # submitted params are exactly as specified. However, POST requests can have request bodies,
    # and request body params override query string params in +r.params+.  So if you are using
    # this for POST requests (or other HTTP verbs that can have request bodies), use +r.GET+
    # instead of +r.params+ to specifically check query string parameters.
    #
    # The generated paths can be timestamped, so that they are only valid until a given time
    # or for a given number of seconds after they are generated, using the +valid_until+ or +seconds+
    # arguments:
    #
    #   hmac_path('/widget/1', valid_until: Time.utc(2100))
    #   # =>  "/dc8b6e56e4cbe7815df7880d42f0e02956b2e4c49881b6060ceb0e49745a540d/t/4102444800/widget/1"
    #
    #   hmac_path('/widget/1', seconds: Time.utc(2100).to_i - Time.now.to_i)
    #   # =>  "/dc8b6e56e4cbe7815df7880d42f0e02956b2e4c49881b6060ceb0e49745a540d/t/4102444800/widget/1"
    #
    # The :namespace option, if provided, should be a string, and it modifies the generated HMACs
    # to only match those in the same namespace.  This can be used to provide different paths to
    # different users or groups of users.
    #
    #   hmac_path('/widget/1', namespace: '1')
    #   # => "/3793ac2a72ea399c40cbd63f154d19f0fe34cdf8d347772134c506a0b756d590/n/widget/1"
    #
    #   hmac_path('/widget/1', namespace: '2')
    #   # => "/0e1e748860d4fd17fe9b7c8259b1e26996502c38e465f802c2c9a0a13000087c/n/widget/1"
    #
    # The +r.hmac_path+ method accepts a +namespace+ argument, and if given,
    # it will only match an hmac path if the namespace given matches the one used
    # when the hmac path was created.
    #
    #   r.hmac_path(namespace: '1'){}
    #   # will match "/3793ac2a72ea399c40cbd63f154d19f0fe34cdf8d347772134c506a0b756d590/n/widget/1"
    #   # will not match "/0e1e748860d4fd17fe9b7c8259b1e26996502c38e465f802c2c9a0a13000087c/n/widget/1"
    #
    # The most common use of the +namespace+ argument is to reference session values, so the value of
    # each path depends on the logged in user.  You can use the +namespace_session_key+ plugin
    # argument to set the default namespace for both +hmac_path+ and +r.hmac_path+:
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       namespace_session_key: 'account_id'
    #
    # This will use <tt>session['account_id']</tt> as the default namespace for both +hmac_path+
    # and +r.hmac_path+ (if the session value is not +nil+, it is converted to a string using +to_s+).
    # You can override the default namespace by passing a +namespace+ argument when calling +hmac_path+
    # and +r.hmac_path+.
    #
    # You can use +root+, +method+, +params+, and +namespace+ arguments at the same time:
    #
    #   hmac_path('/1', root: '/widget', method: :get, params: {foo: 'bar'}, namespace: '1')
    #   # => "/widget/c14c78a81d34d766cf334a3ddbb7a6b231bc2092ef50a77ded0028586027b14e/mpn/1?foo=bar"
    #
    # This gives you a path only valid for a GET request with a root of <tt>/widget</tt> and
    # a query string of <tt>foo=bar</tt>, using namespace +1+.
    #
    # The +resource+ and +action+ arguments bind a signed path to an application resource
    # and action.  They can be given as separate arguments, or together using the +scope+
    # argument with a two element array (or a hash with +resource+ and +action+ keys):
    #
    #   hmac_path('/invoices/1', resource: 'invoice', action: 'read')
    #   hmac_path('/invoices/1', scope: ['invoice', 'read'])
    #   # => "/<hmac>/s/invoices/1"
    #
    # A path signed with a resource and action can only be matched by an +r.hmac_path+
    # call that specifies the same resource and action.  Conversely, paths signed without
    # a resource and action are only matched by +r.hmac_path+ calls that do not specify
    # them.  This allows a receiver to distinguish signed paths for different resources
    # or actions, even when the signed paths use the same root and request method.
    #
    # The +scopes+ plugin argument can restrict the resource/action pairs the application
    # is allowed to sign.  It accepts a hash with resource keys and action (or array of
    # action) values, or an array of resource/action pairs:
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       scopes: {
    #                         'invoice' => 'read',
    #                         'export' => ['submit'],
    #                       }
    #
    # If +scopes+ is provided, +hmac_path+ returns +nil+ without generating a link
    # when asked to sign a path for a resource/action pair that is not configured.
    # Routes that do not use the +resource+ or +action+ arguments are unaffected by
    # the +scopes+ option, so existing signed paths continue to work.
    #
    # In addition to the configured +scopes+, an application can override the
    # +hmac_path_scope_authorized?+ instance method to decide whether the current
    # request is authorized to sign a link for a resource/action pair.  If it
    # returns false, +hmac_path+ returns +nil+ and no link is generated.  The same
    # method is checked when matching a signed path in +r.hmac_path+, so a request
    # that is not authorized for the resource/action will not match the signed path:
    #
    #   def hmac_path_scope_authorized?(resource, action)
    #     current_user.can?(resource, action)
    #   end
    #
    # Note that +r.hmac_path+ requires the matching +resource+ and +action+ to be
    # given for a signed path with the +s+ flag, including paths signed for a
    # +resource+ and +action+ in the past.  Existing paths signed without a
    # +resource+ and +action+ are matched by +r.hmac_path+ calls that also do not
    # specify them, so existing routing trees keep their current behavior.
    #
    # To handle secret rotation, you can provide an +old_secret+ argument when loading the
    # plugin.
    #
    #   plugin :hmac_paths, secret: 'some-secret-value-with-at-least-32-bytes',
    #                       old_secret: 'previous-secret-value-with-at-least-32-bytes'
    #
    # This will use +secret+ for constructing new paths, but will respect paths generated by
    # +old_secret+.
    #
    # = HMAC Construction
    #
    # This describes the internals for how HMACs are constructed based on the options provided
    # to +hmac_path+.  In the examples below:
    #
    # * +HMAC+ is the raw HMAC-SHA256 output (first argument is secret, second is data)
    # * +HMAC_hex+ is the hexidecimal version of +HMAC+
    # * +secret+ is the plugin +secret+ argument
    #
    # The +secret+ plugin argument is never used directly as the HMAC secret.  All HMACs are
    # generated with a root-specific secret.  The root will be the empty if no +root+ argument
    # is given.  The hmac path flags are always included in the hmac calculation, prepended to the
    # path:
    #
    #  r.hmac_path('/1')
    #  HMAC_hex(HMAC_hex(secret, ''), '/0/1')
    # 
    #  r.hmac_path('/1', root: '/2')
    #  HMAC_hex(HMAC_hex(secret, '/2'), '/0/1')
    #
    # The +method+ argument uses an uppercase version of the method prepended to the path. This
    # cannot conflict with the path itself, since paths must start with a slash.
    #
    #  r.hmac_path('/1', method: :get)
    #  HMAC_hex(HMAC_hex(secret, ''), 'GET:/m/1')
    # 
    # The +params+ argument includes the query string for the params in the HMAC:
    #
    #  r.hmac_path('/1', params: {k: 2})
    #  HMAC_hex(HMAC_hex(secret, ''), '/p/1?k=2')
    #
    # The +valid_until+ and +seconds+ arguments include the timestamp in the HMAC:
    #
    #  r.hmac_path('/1', valid_until: Time.utc(2100))
    #  HMAC_hex(HMAC_hex(secret, ''), '/t/4102444800/1')
    #
    # If a +namespace+ argument is provided, the original secret used before the +root+
    # argument is an HMAC of the +secret+ plugin argument and the given namespace.
    # 
    #  r.hmac_path('/1', namespace: '2')
    #  HMAC_hex(HMAC_hex(HMAC(secret, '2'), ''), '/n/1')
    #
    # The +resource+ and +action+ arguments bind the signed path to a resource and
    # action, and are included in the HMAC calculation:
    #
    #  r.hmac_path('/1', resource: 'invoice', action: 'read')
    #  HMAC_hex(HMAC_hex(secret, ''), "invoice\0read:/s/1")
    module HmacPaths
      def self.configure(app, opts=(no_positional_opts = true; OPTS),
          secret: opts[:secret],
          old_secret: opts[:old_secret],
          namespace_session_key: opts[:namespace_session_key],
          scopes: opts[:scopes],
          **kw)
        RodaPlugins.check_keywords("the content_for plugin", no_positional_opts, opts, kw)
        unless secret.is_a?(String) && secret.bytesize >= 32
          raise RodaError, "hmac_paths plugin secret argument must be a string containing at least 32 bytes"
        end

        if old_secret
          unless old_secret.is_a?(String) && old_secret.bytesize >= 32
            raise RodaError, "hmac_paths plugin old_secret argument must be a string containing at least 32 bytes if present"
          end
        end

        app.opts[:hmac_paths_secret] = secret
        app.opts[:hmac_paths_old_secret] = old_secret

        if scopes
          app.opts[:hmac_paths_scopes] = hmac_paths_normalize_scopes(scopes)
        end

        if namespace_session_key
          app.opts[:hmac_paths_namespace_session_key] = namespace_session_key
        end
      end

      # Convert the plugin +scopes+ argument into a frozen hash with resource
      # string keys and frozen arrays of action string values.
      def self.hmac_paths_normalize_scopes(scopes) # :nodoc:
        normalized = {}

        add_scope = proc do |resource, action|
          actions = (normalized[resource.to_s] ||= [])
          action = action.to_s
          actions << action unless actions.include?(action)
        end

        case scopes
        when Hash
          scopes.each do |resource, actions|
            Array(actions).each{|action| add_scope.call(resource, action)}
          end
        when Array
          scopes.each do |scope|
            unless scope.is_a?(Array) && scope.length == 2
              raise RodaError, "hmac_paths plugin scopes array must contain resource/action arrays"
            end
            add_scope.call(*scope)
          end
        else
          raise RodaError, "hmac_paths plugin scopes argument must be a hash or array of resource/action pairs"
        end

        normalized.each_value(&:freeze)
        normalized.freeze
      end

      # Normalize a resource/action pair.  The pair can be provided using a +scope+
      # array or hash, or using separate +resource+ and +action+ keywords.
      def self.hmac_paths_scope_values(scope=nil, resource: nil, action: nil) # :nodoc:
        if scope
          if resource || action
            raise RodaError, "cannot use scope argument with resource or action arguments"
          end

          case scope
          when Array
            unless scope.length == 2
              raise RodaError, "scope array must contain exactly resource and action"
            end
            resource, action = scope
          when Hash
            unless scope.keys.sort == [:action, :resource]
              raise RodaError, "scope hash must contain only resource and action keys"
            end
            resource, action = scope.values_at(:resource, :action)
          else
            raise RodaError, "scope argument must be an array or hash"
          end
        end

        if resource.nil? || action.nil?
          raise RodaError, "resource and action arguments must be provided together"
        end

        resource = resource.to_s
        action = action.to_s

        if resource.empty? || action.empty?
          raise RodaError, "resource and action arguments must be non-empty strings"
        end

        if resource.include?("\0") || action.include?("\0")
          raise RodaError, "resource and action arguments must not contain null bytes"
        end

        [resource, action]
      end

      # Whether the given resource/action pair is allowed by the +scopes+ plugin
      # argument.  If +scopes+ is not configured, all pairs are allowed.
      def self.hmac_paths_scope_allowed?(scopes, resource, action) # :nodoc:
        return true unless scopes

        actions = scopes[resource]
        !!(actions && actions.include?(action))
      end

      module ClassMethods
        RodaPlugins.opt_attr_reader(self, :hmac_paths_secret)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_old_secret)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_namespace_session_key)
        RodaPlugins.opt_attr_reader(self, :hmac_paths_scopes)
      end

      module InstanceMethods
        # Return a path with an HMAC.  Designed to be used with +r.hmac_path+, to make sure
        # users can only request paths that they have been provided by the application
        # (directly or indirectly).  This can prevent users of a site from enumerating
        # valid paths.  The given path should be a string starting with +/+. Keyword Arguments:
        #
        # +method+ :: Limits the returned path to only be valid for the given request method.
        # +namespace+ :: Makes the HMAC value depend on the given namespace. If this is not
        #                provided, the default namespace is used.  To explicitly not use a
        #                namespace when there is a default namespace, pass a nil value.
        # +params+ :: Includes parameters in the query string of the returned path, and
        #             limits the returned path to only be valid for that exact query string.
        # +resource+ :: Binds the returned path to the given application resource.  The
        #               path will only be valid for an +r.hmac_path+ call that specifies
        #               the same resource and action.
        # +action+ :: Binds the returned path to the given application action.
        # +scope+ :: Specify the resource and action together as a two element array
        #            (+[resource, action]+) or a hash with +resource+ and +action+ keys.
        #            Cannot be used together with the +resource+ or +action+ arguments.
        # +root+ :: Should be an empty string or string starting with +/+. This will be
        #           the already matched path of the routing tree using r.hmac_path. Defaults
        #           to the empty string, which will returns paths valid for r.hmac_path at
        #           the top level of the routing tree.
        # +seconds+ :: Make the given path valid for the given integer number of seconds.
        # +valid_until+ :: Make the given path valid until the given Time.
        def hmac_path(path, opts=(no_positional_opts = true; OPTS),
            method: opts[:method],
            namespace: opts.fetch(:namespace){hmac_path_default_namespace},
            params: opts[:params],
            resource: opts[:resource],
            action: opts[:action],
            scope: opts[:scope],
            root: opts[:root] || '',
            seconds: opts[:seconds],
            valid_until: opts[:until],
            **kw)

          if kw.has_key?(:until)
            RodaPlugins.warn("hmac_path until keyword argument is deprecated and will be removed in Roda 4, switch to valid_until argument", uplevel: 1)
            kw_until = kw.delete(:until)
            valid_until ||= kw_until
          end

          RodaPlugins.check_keywords(__callee__, no_positional_opts, opts, kw)

          unless path.is_a?(String) && path.getbyte(0) == 47
            raise RodaError, "path must be a string starting with /"
          end

          unless root.is_a?(String) && ((root_byte = root.getbyte(0)) == 47 || root_byte == nil)
            raise RodaError, "root must be empty string or string starting with /"
          end

          if resource || action || scope
            resource, action = HmacPaths.hmac_paths_scope_values(scope, resource: resource, action: action)
            return unless hmac_path_scope_allowed?(resource, action)
          end

          if valid_until
            valid_until = valid_until.to_i
          elsif seconds
            valid_until = Time.now.to_i + seconds
          end

          flags = String.new
          path = path.dup

          if method
            flags << 'm'
          end

          if params
            flags << 'p'
            path << '?' << Rack::Utils.build_query(params)
          end

          if namespace
            flags << 'n'
          end

          if resource
            flags << 's'
          end

          if valid_until
            flags << 't'
            path = "/#{valid_until}#{path}"
          end

          flags << '0' if flags.empty?

          hmac_path = if method
            "#{method.to_s.upcase}:#{hmac_path_scope_prefix(resource, action)}/#{flags}#{path}"
          else
            "#{hmac_path_scope_prefix(resource, action)}/#{flags}#{path}"
          end

          "#{root}/#{hmac_path_hmac(root, hmac_path, namespace: namespace)}/#{flags}#{path}"
        end

        # The HMAC to use in hmac_path, for the given root, path, namespace, and secret.
        def hmac_path_hmac(root, path, opts=(no_positional_opts = true; OPTS),
            namespace: opts.fetch(:namespace){hmac_path_default_namespace},
            secret: opts[:secret] || self.class.hmac_paths_secret,
            **kw)
          RodaPlugins.check_keywords(__callee__, no_positional_opts, opts, kw)
          hmac_secret = hmac_path_hmac_secret(root, secret: secret, namespace: namespace)
          OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new, hmac_secret, path)
        end

        def hmac_path_namespace(opts=OPTS) # :nodoc:
          RodaPlugins.warn("hmac_path_namespace is deprecated and will be removed in Roda 4", uplevel: 1)
          opts.fetch(:namespace){hmac_path_default_namespace}
        end

        # Whether signing (and matching) a path for the given resource and action is
        # allowed.  Checks both the +scopes+ plugin argument and the
        # +hmac_path_scope_authorized?+ hook.  If either denies the pair, no link is
        # generated and no signed path will match.
        def hmac_path_scope_allowed?(resource, action)
          HmacPaths.hmac_paths_scope_allowed?(self.class.hmac_paths_scopes, resource, action) &&
            hmac_path_scope_authorized?(resource, action)
        end

        # Application hook that can deny signing and matching a path for the given
        # resource and action.  Returns true by default.
        def hmac_path_scope_authorized?(resource, action)
          true
        end

        private

        # The prefix used for the HMAC calculation for a given resource and action.
        # Returns an empty string if no resource is used.
        def hmac_path_scope_prefix(resource, action)
          resource ? "#{resource}\0#{action}" : ''
        end

        # The secret used to calculate the HMAC in hmac_path. This is itself an HMAC, created
        # using the secret given in the plugin, for the given root, namespace, and secret.
        # This always returns a hexidecimal string.
        def hmac_path_hmac_secret(root, opts=(no_positional_opts = true; OPTS),
            namespace: (
              RodaPlugins.warn("hmac_path_hmac_secret namespace argument will be required in Roda 4", uplevel: 1);
              opts.fetch(:namespace){hmac_path_default_namespace}
            ),
            secret: (
              RodaPlugins.warn("hmac_path_hmac_secret secret argument will be required in Roda 4", uplevel: 1);
              opts[:secret] || self.class.hmac_paths_secret
            ),
            **kw)
          RodaPlugins.check_keywords(__callee__, no_positional_opts, opts, kw)

          if namespace
            secret = OpenSSL::HMAC.digest(OpenSSL::Digest::SHA256.new, secret, namespace)
          end

          OpenSSL::HMAC.hexdigest(OpenSSL::Digest::SHA256.new, secret, root)
        end

        # The default namespace to use for hmac_path, if a namespace argument is not provided.
        def hmac_path_default_namespace
          if (key = self.class.hmac_paths_namespace_session_key) && (value = session[key])
            value.to_s
          end
        end
      end

      module RequestMethods
        # Looks at the first segment of the remaining path, and if it contains a valid HMAC for the
        # rest of the path considering the flags in the second segment and the namespace, the
        # block matches and is yielded to, and the result of the block is returned. Otherwise, the
        # block does not matches and routing continues after the call.
        #
        # If +resource+ and +action+ are given (or +scope+ with a two element array or hash),
        # only matches a path that was signed for the same resource and action.  Paths signed
        # without a resource and action are only matched when no resource and action are given.
        def hmac_path(opts=(no_positional_opts = true; OPTS),
            namespace: opts.fetch(:namespace){scope.send(:hmac_path_default_namespace)},
            resource: opts[:resource],
            action: opts[:action],
            scope: opts[:scope],
            **kw, &block)
          RodaPlugins.check_keywords(__callee__, no_positional_opts, opts, kw)

          request_scope = @scope

          if resource || action || scope
            resource, action = HmacPaths.hmac_paths_scope_values(scope, resource: resource, action: action)
            unless request_scope.send(:hmac_path_scope_allowed?, resource, action)
              return
            end
          end

          orig_path = remaining_path
          mpath = matched_path

          on String do |submitted_hmac|
            rpath = remaining_path

            if submitted_hmac.bytesize == 64
              on String do |flags|
                if flags.include?('n') ^ !namespace.nil?
                  # Namespace required and not provided, or provided and not required.
                  # Bail early to avoid unnecessary HMAC calculation.
                  @remaining_path = orig_path
                  return
                end

                if flags.include?('s') ^ !resource.nil?
                  # Resource/action required and not provided, or provided and not required.
                  # Bail early to avoid unnecessary HMAC calculation.
                  @remaining_path = orig_path
                  return
                end

                method_prefix = flags.include?('m') ? "#{env['REQUEST_METHOD'].to_s.upcase}:" : ''
                scope_prefix = resource ? request_scope.send(:hmac_path_scope_prefix, resource, action) : ''

                rpath = "#{method_prefix}#{scope_prefix}#{rpath}"

                if flags.include?('p')
                  rpath = "#{rpath}?#{env["QUERY_STRING"]}"
                end

                if hmac_path_valid?(mpath, rpath, submitted_hmac, namespace: namespace)
                  if flags.include?('t')
                    on Integer do |int|
                      if int >= Time.now.to_i
                        always(&block)
                      else
                        # Return from method without matching
                        @remaining_path = orig_path
                        return
                      end
                    end
                  else
                    always(&block)
                  end
                end
              end

              # Return from method without matching
              @remaining_path = orig_path
              return
            end

            # Return from method without matching
            @remaining_path = orig_path
            return
          end
        end

        private

        # Determine whether the provided hmac matches.
        def hmac_path_valid?(root, path, hmac, opts=(no_positional_opts = true; OPTS),
            namespace: (
              RodaPlugins.warn("hmac_path_valid? namespace argument will be required in Roda 4", uplevel: 1);
              opts.fetch(:namespace){scope.send(:hmac_path_default_namespace)}
            ),
            **kw)
          RodaPlugins.check_keywords(__callee__, no_positional_opts, opts, kw)

          if Rack::Utils.secure_compare(scope.hmac_path_hmac(root, path, namespace: namespace, secret: roda_class.hmac_paths_secret), hmac)
            true
          elsif old_secret = roda_class.hmac_paths_old_secret
            Rack::Utils.secure_compare(scope.hmac_path_hmac(root, path, namespace: namespace, secret: old_secret), hmac)
          else
            false
          end
        end
      end
    end

    register_plugin(:hmac_paths, HmacPaths)
  end

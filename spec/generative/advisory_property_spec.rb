require 'spec_helper'
require 'bundler/audit/advisory'
require 'bundler/audit/database'
require 'bundler/audit/scanner'
require 'bundler/audit/results/unpatched_gem'

require 'tmpdir'
require 'yaml'

require_relative 'version_model'
require_relative 'generators'
require_relative 'harness'

describe 'Advisory version-affecting properties' do
  GEM_NAME = 'property-test-gem'.freeze

  # Fixed default seed so every run is reproducible. Override with
  # PROP_SEED / PROP_ITERATIONS to explore or to replay a failure.
  DEFAULT_SEED     = 20_261_114
  DEFAULT_ITERATIONS = 100

  # Seeds worth replaying on every run. Seed 2 is the recorded seed of
  # the generative run that catches the artificially introduced ">= -> >"
  # boundary bug below.
  RECORDED_SEEDS = [DEFAULT_SEED, 7, 42, 613].freeze

  # Seed used by the injected-boundary-bug sample: iteration 4 generates
  # patched [">= 2.1.1", ">= 0.1.0.beta2", ...], and the harness reports
  # the pre-release boundary version "0.1.0.beta2".
  BUG_SEED = 2

  let(:tmpdirs) { [] }

  after do
    tmpdirs.each { |dir| FileUtils.rm_rf(dir) }
  end

  # Writes an advisory YAML for the given ranges into a fresh temporary
  # database directory and returns [database_dir, advisory_path].
  def write_advisory(patched, unaffected, tmpdirs, include_empty_keys: true)
    dir = Dir.mktmpdir('property-db-', Fixtures::TMP_DIR)
    tmpdirs << dir

    data = {
      'gem'         => GEM_NAME,
      'cve'         => '2099-0001',
      'url'         => 'https://example.com/',
      'title'       => 'Generated property-test advisory',
      'date'        => Date.new(2026, 1, 1),
      'description' => 'Generated by the generative property tests.'
    }

    if include_empty_keys || !unaffected.empty?
      data['unaffected_versions'] = unaffected
    end
    if include_empty_keys || !patched.empty?
      data['patched_versions'] = patched
    end

    gem_dir = File.join(dir, 'gems', GEM_NAME)
    FileUtils.mkdir_p(gem_dir)

    path = File.join(gem_dir, 'CVE-2099-0001.yml')
    File.write(path, YAML.dump(data))

    [dir, path]
  end

  def gem_spec(version)
    Gem::Specification.new do |spec|
      spec.name    = GEM_NAME
      spec.version = version
    end
  end

  # Layer: Advisory#vulnerable? after a real YAML load.
  def advisory_verdict(tmpdirs)
    lambda do |patched, unaffected|
      _dir, path = write_advisory(patched, unaffected, tmpdirs)
      advisory   = Bundler::Audit::Advisory.load(path)

      ->(point) { advisory.vulnerable?(Gem::Version.new(point)) }
    end
  end

  # Layer: the final scan result, Database#check_gem (what
  # Scanner#scan_specs uses to decide whether a gem is flagged).
  def check_gem_verdict(tmpdirs)
    lambda do |patched, unaffected|
      dir, _path = write_advisory(patched, unaffected, tmpdirs)
      database   = Bundler::Audit::Database.new(dir)

      ->(point) { database.check_gem(gem_spec(point)).any? }
    end
  end

  def lockfile_for(version)
    <<~LOCKFILE
      GEM
        remote: https://rubygems.org/
        specs:
          #{GEM_NAME} (#{version})

      PLATFORMS
        ruby

      DEPENDENCIES
        #{GEM_NAME}

      BUNDLED WITH
         2.2.0
    LOCKFILE
  end

  # Layer: the end-to-end Scanner over a generated Gemfile.lock.
  def scanner_flagged?(database_dir, point)
    Dir.mktmpdir('property-bundle-', Fixtures::TMP_DIR) do |bundle_dir|
      File.write(File.join(bundle_dir, 'Gemfile.lock'), lockfile_for(point))

      scanner = Bundler::Audit::Scanner.new(bundle_dir, 'Gemfile.lock', Bundler::Audit::Database.new(database_dir))
      results = scanner.scan.select { |result| result.is_a?(Bundler::Audit::Results::UnpatchedGem) }

      results.any?
    end
  end

  # Layer: YAML load + Gem::Requirement parsing. Verifies the entries
  # round-trip through the YAML file and that every parsed requirement
  # matches the reference model on every probe point.
  def check_yaml_and_requirement_layer(generated_case)
    _dir, path = write_advisory(generated_case.patched, generated_case.unaffected, tmpdirs)
    advisory   = Bundler::Audit::Advisory.load(path)

    expect(advisory.patched_versions.map(&:to_s)).to eq(generated_case.patched)
    expect(advisory.unaffected_versions.map(&:to_s)).to eq(generated_case.unaffected)

    {
      'patched'    => [generated_case.patched, advisory.patched_versions],
      'unaffected' => [generated_case.unaffected, advisory.unaffected_versions]
    }.each do |kind, (entries, requirements)|
      requirements.each_with_index do |requirement, index|
        generated_case.points.each do |point|
          actual   = requirement === Gem::Version.new(point)
          expected = Generative::VersionModel.requirement_satisfied?(entries[index], point)

          expect(actual).to eq(expected),
            "#{kind} requirement #{entries[index].inspect} parsed as #{requirement.inspect} " \
            "disagrees with the reference model on version #{point.inspect}: " \
            "parsed=#{actual} reference=#{expected}"
        end
      end
    end
  end

  def run_property(seed:, iterations:, verdict_builder: nil, scanner_sample: true)
    verdict_builder ||= advisory_verdict(tmpdirs)
    generator         = Generative::Generators.new(seed)

    iterations.times do |iteration|
      generated_case = generator.advisory_case

      check_yaml_and_requirement_layer(generated_case)

      Generative::Harness.check(
        patched:    generated_case.patched,
        unaffected: generated_case.unaffected,
        points:     generated_case.points,
        seed:       seed,
        iteration:  iteration,
        layer:      'Advisory#vulnerable? / Database#check_gem',
        build_actual: verdict_builder
      )

      # End-to-end Scanner cross-check on a sample of iterations.
      if scanner_sample && (iteration % 10).zero?
        dir, _path = write_advisory(generated_case.patched, generated_case.unaffected, tmpdirs)

        generated_case.points.sample(3, random: generator.random).each do |point|
          expected = Generative::VersionModel.vulnerable?(generated_case.patched, generated_case.unaffected, point)
          actual   = scanner_flagged?(dir, point)

          expect(actual).to eq(expected),
            "Scanner flagged #{GEM_NAME} #{point.inspect} as vulnerable=#{actual} " \
            "but the reference model says vulnerable=#{expected} " \
            "(patched: #{generated_case.patched.inspect}, unaffected: #{generated_case.unaffected.inspect}, " \
            "seed: #{seed}, iteration: #{iteration})"
        end
      end
    end
  end

  describe 'reference model self-check' do
    it 'agrees with Gem::Version comparison on generated version pairs' do
      generator = Generative::Generators.new(DEFAULT_SEED)

      200.times do
        version_a = generator.version
        version_b = generator.version

        expect(Generative::VersionModel.compare(version_a, version_b)).to(
          eq(Gem::Version.new(version_a) <=> Gem::Version.new(version_b)),
          "reference comparison of #{version_a.inspect} <=> #{version_b.inspect} diverges from Gem::Version"
        )
      end
    end

    it 'agrees with Gem::Requirement matching on generated constraints' do
      generator = Generative::Generators.new(DEFAULT_SEED + 1)

      200.times do
        constraint = generator.constraint
        point      = generator.version

        expect(Generative::VersionModel.constraint_satisfied?(constraint, point)).to(
          eq(Gem::Requirement.new(constraint) === Gem::Version.new(point)),
          "reference matching of #{constraint.inspect} against #{point.inspect} diverges from Gem::Requirement"
        )
      end
    end
  end

  describe 'generative property' do
    it 'matches the reference model across YAML load, requirement parsing, and the final scan result' do
      seed       = Integer(ENV.fetch('PROP_SEED', DEFAULT_SEED))
      iterations = Integer(ENV.fetch('PROP_ITERATIONS', DEFAULT_ITERATIONS))

      run_property(seed: seed, iterations: iterations)
    end

    it 'replays the recorded seeds' do
      RECORDED_SEEDS.each do |seed|
        run_property(seed: seed, iterations: 20)
      end
    end
  end

  describe 'hand-written pre-release anchors' do
    # Each anchor is [patched, unaffected, point, expected_vulnerable].
    anchors = [
      # a pre-release sorts before its release boundary: ">= 1.0.0" does
      # not cover "1.0.0.pre1", so the pre-release stays vulnerable
      [['>= 1.0.0'], [], '1.0.0.pre1', true],
      [['>= 1.0.0'], [], '1.0.0', false],
      # an inclusive pre-release boundary covers exactly that pre-release
      [['>= 1.0.0.pre1'], [], '1.0.0.pre1', false],
      [['>= 1.0.0.pre1'], [], '1.0.0.pre0', true],
      [['>= 1.0.0.pre1'], [], '1.0.0', false],
      # "~> 1.2" ends at "< 2" compared against the *release* of the
      # version: the release of "2.0.0.pre1" is "2.0.0", which is not
      # below 2, so the pre-release is NOT covered
      [['~> 1.2'], [], '2.0.0.pre1', true],
      [['~> 1.2'], [], '1.4.0.pre1', false],
      [['~> 1.2'], [], '2.0.0', true],
      # "~> 1.2.3" ends at "< 1.3", again compared against the release
      [['~> 1.2.3'], [], '1.3.0.pre1', true],
      [['~> 1.2.3'], [], '1.2.9.pre1', false],
      [['~> 1.2.3'], [], '1.3.0', true],
      [['~> 1.2.3'], [], '1.2.3.pre1', true],
      # unaffected ranges follow the same pre-release ordering
      [[], ['< 1.0.0'], '1.0.0.pre1', false],
      [[], ['< 1.0.0'], '1.0.0', true],
      # trailing zero segments are equal
      [['= 1.0'], [], '1.0.0', false],
      [['= 1.0'], [], '1.0.0.pre1', true],
      # exclusive boundaries exclude the boundary itself
      [['> 1.2'], [], '1.2', true],
      [['> 1.2'], [], '1.2.1', false],
      # overlapping patched ranges cover their union
      [['>= 1.0, < 1.5', '>= 1.4, < 2.0'], [], '1.4.5', false],
      [['>= 1.0, < 1.5', '>= 1.4, < 2.0'], [], '1.3.0', false],
      [['>= 1.0, < 1.5', '>= 1.4, < 2.0'], [], '1.9.9', false],
      [['>= 1.0, < 1.5', '>= 1.4, < 2.0'], [], '2.0.0', true],
      [['>= 1.0, < 1.5', '>= 1.4, < 2.0'], [], '0.9.9', true],
      # "!= 1.1" patches everything except 1.1 itself
      [['!= 1.1'], [], '1.1', true],
      [['!= 1.1'], [], '1.1.0.pre1', false]
    ]

    anchors.each do |patched, unaffected, point, expected|
      it "treats #{point.inspect} as vulnerable=#{expected} for patched=#{patched.inspect} unaffected=#{unaffected.inspect}" do
        expect(Generative::VersionModel.vulnerable?(patched, unaffected, point)).to eq(expected),
          "reference model expectation is wrong for #{point.inspect}"

        _dir, path = write_advisory(patched, unaffected, tmpdirs)
        advisory   = Bundler::Audit::Advisory.load(path)

        expect(advisory.vulnerable?(Gem::Version.new(point))).to eq(expected)

        database_dir, = write_advisory(patched, unaffected, tmpdirs)
        database      = Bundler::Audit::Database.new(database_dir)

        expect(database.check_gem(gem_spec(point)).any?).to eq(expected)
      end
    end
  end

  describe 'advisories without any patch' do
    it 'treats every version as affected when patched_versions is empty' do
      points = ['0.1', '1.0.0', '1.0.0.pre1', '4.3.2']

      _dir, path = write_advisory([], [], tmpdirs)
      advisory   = Bundler::Audit::Advisory.load(path)

      points.each do |point|
        expect(advisory.vulnerable?(Gem::Version.new(point))).to be(true),
          "expected #{point.inspect} to be affected by an unpatched advisory"
      end
    end

    it 'treats every version as affected when the version keys are absent from the YAML' do
      database_dir, path = write_advisory([], [], tmpdirs, include_empty_keys: false)

      expect(YAML.safe_load(File.read(path), permitted_classes: [Date])).not_to have_key('patched_versions')

      advisory = Bundler::Audit::Advisory.load(path)
      database = Bundler::Audit::Database.new(database_dir)

      ['0.1', '1.0.0', '1.0.0.pre1'].each do |point|
        expect(advisory.vulnerable?(Gem::Version.new(point))).to be(true)
        expect(database.check_gem(gem_spec(point)).any?).to be(true)
      end
    end

    it 'keeps flagging unpatched advisories in generated cases' do
      # generated cases with empty patched and unaffected ranges must
      # flag every probe point
      generator = Generative::Generators.new(DEFAULT_SEED + 2)

      20.times do
        generated_case = generator.advisory_case
        next unless generated_case.patched.empty? && generated_case.unaffected.empty?

        Generative::Harness.check(
          patched:    [],
          unaffected: [],
          points:     generated_case.points,
          seed:       DEFAULT_SEED + 2,
          iteration:  0,
          layer:      'unpatched advisory',
          build_actual: check_gem_verdict(tmpdirs)
        )
      end
    end
  end

  describe 'artificially introduced boundary bug' do
    # Simulates an off-by-one boundary error: ">=" constraints in
    # patched_versions are evaluated as ">". The harness must catch the
    # divergence and name the exact boundary version.
    def buggy_verdict(tmpdirs)
      lambda do |patched, unaffected|
        buggy_patched = patched.map { |entry| entry.gsub(/>= /, '> ') }
        _dir, path    = write_advisory(buggy_patched, unaffected, tmpdirs)
        advisory      = Bundler::Audit::Advisory.load(path)

        ->(point) { advisory.vulnerable?(Gem::Version.new(point)) }
      end
    end

    it 'is caught on a hand-built boundary case and reports the exact version' do
      expect {
        Generative::Harness.check(
          patched:    ['>= 1.2.0'],
          unaffected: [],
          points:     ['1.1.9', '1.2.0', '1.2.1'],
          seed:       BUG_SEED,
          iteration:  0,
          layer:      'injected >= -> > bug',
          build_actual: buggy_verdict(tmpdirs)
        )
      }.to raise_error(Generative::PropertyFailure) do |error|
        # shrinking may reduce "1.2.0" to the equal but simpler "1.2"
        expect(Generative::VersionModel.compare(error.point, '1.2.0')).to eq(0)
        expect(error.expected).to be(false)
        expect(error.actual).to be(true)
        expect(error.message).to include(error.point.inspect)
      end
    end

    # Simulates the opposite boundary error: "<" constraints in
    # unaffected_versions are evaluated as "<=", so the boundary version
    # is wrongly considered unaffected and the vulnerability is missed.
    def buggy_unaffected_verdict(tmpdirs)
      lambda do |patched, unaffected|
        buggy_unaffected = unaffected.map { |entry| entry.gsub(/< /, '<= ') }
        _dir, path       = write_advisory(patched, buggy_unaffected, tmpdirs)
        advisory         = Bundler::Audit::Advisory.load(path)

        ->(point) { advisory.vulnerable?(Gem::Version.new(point)) }
      end
    end

    it 'reports the exact version of a missed vulnerability (unaffected < becomes <=)' do
      expect {
        Generative::Harness.check(
          patched:    [],
          unaffected: ['< 1.2.0'],
          points:     ['1.1.9', '1.2.0', '1.2.1'],
          seed:       BUG_SEED,
          iteration:  0,
          layer:      'injected < -> <= bug',
          build_actual: buggy_unaffected_verdict(tmpdirs)
        )
      }.to raise_error(Generative::PropertyFailure) do |error|
        expect(Generative::VersionModel.compare(error.point, '1.2.0')).to eq(0)
        expect(error.expected).to be(true)
        expect(error.actual).to be(false)
        expect(error.message).to include('missed vulnerability')
      end
    end

    it "is caught by the generative run on the recorded seed #{BUG_SEED}" do
      expect {
        run_property(
          seed:            BUG_SEED,
          iterations:       30,
          verdict_builder:  buggy_verdict(tmpdirs),
          scanner_sample:   false
        )
      }.to raise_error(Generative::PropertyFailure) do |error|
        # the reported version must sit exactly on a generated boundary
        bounds = (error.patched + error.unaffected).flat_map do |entry|
          entry.scan(/(?:=|!=|>=?|<=?|~>)\s*(\S+)/).flatten
        end

        expect(error.actual).not_to eq(error.expected)
        expect(error.message).to include(error.point.inspect)
        expect(bounds).not_to be_empty
      end
    end
  end
end

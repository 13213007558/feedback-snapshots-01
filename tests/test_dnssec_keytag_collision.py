"""Regression tests: a DNSKEY key tag is not a unique key identity.

The 16-bit key tag (RFC 4034 appendix B) collides easily, so RRSIG
validation must always check the candidate's *full* public key against
the signature and must never treat a key-tag match (or a previously
validated key with the same tag) as proof of identity.

The fixtures in ``tests/dnsseckeys/keytag-collision/`` are two real
ECDSAP256SHA256 zone keys for ``keytag-collision.example`` with the same
key tag but different public keys, generated by
``tests/dnsseckeys/make-keytag-collision.py``.  Key "a" is the
legitimate signing key; key "b" is the confusable impostor.
"""

import unittest.mock
from datetime import datetime, timezone
from pathlib import Path

import pytest

import dns.dnssec
import dns.name
import dns.rrset
from dns.dnssectypes import Algorithm

if dns.dnssec._have_pyca:
    from cryptography.exceptions import InvalidSignature

    from dns.dnssecalgs.serialization import Key

pytestmark = pytest.mark.skipif(
    not dns.dnssec._have_pyca, reason="Python Cryptography cannot be imported"
)

FIXTURE_DIRECTORY = Path(__file__).parent / "dnsseckeys" / "keytag-collision"

OWNER = dns.name.from_text("keytag-collision.example")

INCEPTION = datetime(2020, 1, 1, tzinfo=timezone.utc)
EXPIRATION = datetime(2037, 1, 1, tzinfo=timezone.utc)
NOW = datetime(2026, 11, 18, tzinfo=timezone.utc).timestamp()

RRSET = dns.rrset.from_text(OWNER, 3600, "IN", "A", "192.0.2.1")


def _load_key(suffix: str) -> "Key":
    stem = next(FIXTURE_DIRECTORY.glob(f"K*-{suffix}.private")).name[: -len(".private")]
    return Key.from_bind_bytes(
        private_data=(FIXTURE_DIRECTORY / f"{stem}.private").read_bytes(),
        public_data=(FIXTURE_DIRECTORY / f"{stem}.key").read_bytes(),
    )


@pytest.fixture(scope="module")
def key_a() -> "Key":
    """The legitimate key, whose private key signs the test RRset."""
    return _load_key("a")


@pytest.fixture(scope="module")
def key_b() -> "Key":
    """The impostor key: same name, algorithm, and key tag as key_a."""
    return _load_key("b")


@pytest.fixture(scope="module")
def rrsig_a(key_a) -> dns.rdata.Rdata:
    """An independently generated signature over RRSET made with key_a."""
    return dns.dnssec.sign(
        RRSET,
        key_a.private,
        OWNER,
        key_a.dnskey,
        inception=INCEPTION,
        expiration=EXPIRATION,
    )


@pytest.fixture(scope="module")
def rrsig_b(key_b) -> dns.rdata.Rdata:
    """An independently generated signature over RRSET made with key_b."""
    return dns.dnssec.sign(
        RRSET,
        key_b.private,
        OWNER,
        key_b.dnskey,
        inception=INCEPTION,
        expiration=EXPIRATION,
    )


def _keys_rrset(*keys: "Key") -> dns.rrset.RRset:
    return dns.rrset.from_rdata(OWNER, 3600, *(k.dnskey for k in keys))


def _validate(rrset, rrsig, keys, policy=None):
    rrsigset = dns.rrset.from_rdata(RRSET.name, 3600, rrsig)
    dns.dnssec.validate(rrset, rrsigset, keys, None, NOW, policy=policy)


def test_fixture_keys_collide_on_key_tag(key_a, key_b):
    """The fixtures must actually collide: same name, algorithm, and key
    tag, but different public keys."""
    assert key_a.name == key_b.name == OWNER
    assert key_a.dnskey.algorithm == key_b.dnskey.algorithm == Algorithm.ECDSAP256SHA256
    assert key_a.dnskey.flags == key_b.dnskey.flags
    assert key_a.dnskey.protocol == key_b.dnskey.protocol == 3
    assert key_a.key_id() == key_b.key_id()
    assert key_a.dnskey.key != key_b.dnskey.key
    assert key_a.public.to_pem() != key_b.public.to_pem()


def test_key_tag_match_does_not_disambiguate_candidates(key_a, key_b, rrsig_a):
    """Both keys are candidates for the same RRSIG, so the key tag alone
    cannot identify the verifying key."""
    keys = {OWNER: _keys_rrset(key_a, key_b)}
    candidates = dns.dnssec._find_candidate_keys(keys, rrsig_a)
    assert [c.key for c in candidates] == [key_a.dnskey.key, key_b.dnskey.key]


def test_signature_verifies_against_full_public_key(key_a, key_b, rrsig_a):
    """The signature over RRSET verifies with key_a's full public key and
    fails with key_b's, even though both share a key tag."""
    data = dns.dnssec._make_rrsig_signature_data(RRSET, rrsig_a, None)
    key_a.public.verify(rrsig_a.signature, data)
    with pytest.raises(InvalidSignature):
        key_b.public.verify(rrsig_a.signature, data)


def test_validate_legitimate_key_first(key_a, key_b, rrsig_a):
    _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_a, key_b)})


def test_validate_legitimate_key_last(key_a, key_b, rrsig_a):
    """Candidate order must not matter: the same independently generated
    signature validates when the legitimate key is tried last."""
    _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_b, key_a)})


def test_validate_legitimate_key_absent(key_b, rrsig_a):
    """With only the colliding impostor key present, validation must fail
    even though the key tag matches the RRSIG."""
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_b)})


def test_validate_no_keys(rrsig_a):
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(RRSET, rrsig_a, {})


def test_impostor_signature_only_validates_with_impostor_key(key_a, key_b, rrsig_b):
    """A signature made by the impostor key validates with the impostor
    key but never with the legitimate key, proving validation binds the
    signature to the full public key and not to the shared key tag."""
    _validate(RRSET, rrsig_b, {OWNER: _keys_rrset(key_b)})
    _validate(RRSET, rrsig_b, {OWNER: _keys_rrset(key_a, key_b)})
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(RRSET, rrsig_b, {OWNER: _keys_rrset(key_a)})


def test_successful_validation_uses_full_public_key(key_a, key_b, rrsig_a):
    """Spy on the low-level verifier to prove the full public key (not a
    key-tag match) is what actually verifies the signature."""
    attempts = []
    real_validate_signature = dns.dnssec._validate_signature

    def spy(sig, data, key):
        try:
            real_validate_signature(sig, data, key)
        except Exception as e:
            attempts.append((key.key, sig, e))
            raise
        attempts.append((key.key, sig, None))

    with unittest.mock.patch.object(dns.dnssec, "_validate_signature", spy):
        _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_b, key_a)})

    # The impostor is tried first and fails; the legitimate key is tried
    # next and succeeds.  Both attempts see the real signature bytes.
    assert attempts == [
        (key_b.dnskey.key, rrsig_a.signature, unittest.mock.ANY),
        (key_a.dnskey.key, rrsig_a.signature, None),
    ]
    assert isinstance(attempts[0][2], InvalidSignature)


def test_prior_tag_match_success_is_not_reused(key_a, key_b, rrsig_a, rrsig_b):
    """Guard against identity confusion from caching validated keys by
    key tag: after a successful validation with key_a, substituting the
    same-tag impostor key_b must still fail, and vice versa.  If a
    candidate cache were keyed only by (signer, algorithm, key tag), the
    second validation in each pair would wrongly succeed."""
    _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_a)})
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(RRSET, rrsig_a, {OWNER: _keys_rrset(key_b)})

    _validate(RRSET, rrsig_b, {OWNER: _keys_rrset(key_b)})
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(RRSET, rrsig_b, {OWNER: _keys_rrset(key_a)})


def test_algorithm_policy_still_enforced(key_a, key_b, rrsig_a):
    """Normal algorithm policy keeps applying to colliding keys: denying
    the algorithm rejects validation even with the legitimate key."""
    deny_ecdsa = dns.dnssec.SimpleDeny(set(), {Algorithm.ECDSAP256SHA256}, set(), set())
    with pytest.raises(dns.dnssec.ValidationFailure):
        _validate(
            RRSET,
            rrsig_a,
            {OWNER: _keys_rrset(key_a, key_b)},
            policy=deny_ecdsa,
        )

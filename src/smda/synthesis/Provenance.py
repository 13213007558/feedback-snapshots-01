"""Provenance manifest for synthesized binaries.

A synthesized PE/ELF/Mach-O is a fictive container built for similarity tooling,
not a recovered original: some of its bytes come from the report (recovered basic
blocks, referenced strings, import slot addresses) and everything else is newly
generated structure (headers, NOP fill, alignment padding, import tables, IAT gap
and terminator slots, string terminators). The manifest enumerates the recovered
ranges so a backend can store next to the synthesized bytes exactly which VAs
carry recovered content; any byte outside the listed regions is generated by
construction (``default_origin``).

The manifest is a pure function of report content: building it never mutates the
report, and it does not consult the stored buffer, so ``STORE_BUFFER`` has no
effect on it -- exactly as it has none on synthesis itself.
"""

import hashlib

from smda.synthesis.BinarySynthesizer import BinarySynthesizer

PROVENANCE_KIND = "smda.synthesis.provenance"
PROVENANCE_FORMAT_VERSION = 1

ORIGIN_RECOVERED_BLOCK = "recovered_block"
ORIGIN_RECOVERED_STRING = "recovered_string"
ORIGIN_IMPORT_SLOT = "import_slot"
ORIGIN_GENERATED = "generated"

#: The classes of structure a synthesizer writes that never come from the report.
GENERATED_STRUCTURES = [
    "file_headers",
    "section_alignment_padding",
    "nop_fill",
    "import_tables",
    "iat_gap_padding",
    "iat_terminators",
    "string_terminators",
]

MANIFEST_NOTES = [
    "a synthesized binary is a fictive container for similarity analysis, not a recovered original file",
    "any byte outside the listed regions is generated; the manifest makes no claim about the original file's layout",
    "import slot addresses come from report metadata, but the thunk content written into them is generated",
    "an import slot that fits no data section may be relocated by the synthesizer; the reported address is listed here",
    "synthesis is deterministic from report content only and does not consult the stored buffer (STORE_BUFFER)",
]


def _findConflicts(code_regions):
    """Overlaps between recovered block ranges, in planting order.

    Blocks are planted per function in ascending function offset, and per block in
    ascending block offset, so where two ranges claim the same address the later
    planting wins. Well-formed reports never overlap (the CFG model forbids it);
    a hand-built one can, and the conflict has to be recorded rather than hidden.
    """
    conflicts = []
    ordered = sorted(range(len(code_regions)), key=lambda index: code_regions[index]["va_start"])
    active = []
    for index in ordered:
        region = code_regions[index]
        active = [other for other in active if code_regions[other]["va_end"] > region["va_start"]]
        for other in active:
            earlier = code_regions[other]
            conflicts.append(
                {
                    "va_start": max(region["va_start"], earlier["va_start"]),
                    "va_end": min(region["va_end"], earlier["va_end"]),
                    "winner": {
                        "function_offset": region["function_offset"],
                        "block_offset": region["block_offset"],
                    },
                    "overwritten": {
                        "function_offset": earlier["function_offset"],
                        "block_offset": earlier["block_offset"],
                    },
                }
            )
        active.append(index)
    return conflicts


def buildProvenanceManifest(report, function_offsets=None, with_imports=True, with_strings=True) -> dict:
    """Builds the JSON-serializable provenance manifest for what synthesis would plant.

    Recovered regions carry their expected content hash so an independent reader
    can verify a synthesized file against the manifest without trusting the
    synthesizer. The manifest is format-agnostic: it describes the address space
    the PE/ELF/Mach-O synthesizers all plant into, not one file's layout.
    """
    synthesizer = BinarySynthesizer(report)
    offsets = synthesizer._resolveFunctionOffsets(function_offsets)

    regions = []
    code_regions = []
    for function_offset in offsets:
        for block_offset, chunk in synthesizer._iterFunctionChunks(report.xcfg[function_offset]):
            region = {
                "origin": ORIGIN_RECOVERED_BLOCK,
                "va_start": block_offset,
                "va_end": block_offset + len(chunk),
                "size": len(chunk),
                "sha256": hashlib.sha256(chunk).hexdigest(),
                "function_offset": function_offset,
                "block_offset": block_offset,
            }
            code_regions.append(region)
            regions.append(region)

    if with_strings:
        for data_addr, content in synthesizer._iterStringRefContents():
            regions.append(
                {
                    "origin": ORIGIN_RECOVERED_STRING,
                    "va_start": data_addr,
                    "va_end": data_addr + len(content),
                    "size": len(content),
                    "sha256": hashlib.sha256(content).hexdigest(),
                }
            )

    if with_imports:
        pointer_size = 8 if report.bitness == 64 else 4
        for address, (dll, name) in sorted(synthesizer._getImportMap().items()):
            regions.append(
                {
                    "origin": ORIGIN_IMPORT_SLOT,
                    "va_start": address,
                    "va_end": address + pointer_size,
                    "size": pointer_size,
                    "dll": dll,
                    "name": name,
                    "content_origin": ORIGIN_GENERATED,
                }
            )

    regions.sort(key=lambda region: (region["va_start"], region["va_end"]))
    return {
        "kind": PROVENANCE_KIND,
        "format_version": PROVENANCE_FORMAT_VERSION,
        "architecture": report.architecture,
        "base_addr": report.base_addr,
        "regions": regions,
        "conflicts": _findConflicts(code_regions),
        "default_origin": ORIGIN_GENERATED,
        "generated_structures": list(GENERATED_STRUCTURES),
        "notes": list(MANIFEST_NOTES),
    }

from __future__ import annotations

import dataclasses
import functools
import inspect
import re
import typing as t
import weakref
from time import perf_counter

import sqlalchemy as sa
import sqlalchemy.event as sa_event
from flask import current_app
from flask import Flask
from flask import g
from flask import has_app_context


def get_recorded_queries() -> list[_QueryInfo]:
    """Get the list of recorded query information for the current session. Queries are
    recorded if the config :data:`.SQLALCHEMY_RECORD_QUERIES` is enabled.

    Each query info object has the following attributes:

    ``statement``
        The string of SQL generated by SQLAlchemy with parameter placeholders.
    ``parameters``
        The parameters sent with the SQL statement. If a
        :data:`.SQLALCHEMY_RECORD_QUERY_PARAMS` policy restricts them, allowed values
        are kept and the others are replaced with ``"***"``. When restricted, this is
        a list of dicts mapping parameter names to values. When not restricted, this
        keeps the form the driver used.
    ``start_time`` / ``end_time``
        Timing info about when the query started execution and when the results where
        returned. Accuracy and value depends on the operating system.
    ``duration``
        The time the query took in seconds.
    ``location``
        A string description of where in your application code the query was executed.
        This may not be possible to calculate, and the format is not stable.
    ``bind_key``
        The bind key of the engine that ran the query. ``None`` is the default bind.
    ``parameters_restricted``
        Whether parameter values were restricted by the app's policy.

    .. versionchanged:: 3.2
        Parameter recording can be restricted per app and bind with
        :data:`.SQLALCHEMY_RECORD_QUERY_PARAMS`. Added ``bind_key`` and
        ``parameters_restricted``. A query that raises an error is not added to the
        list.

    .. versionchanged:: 3.0
        Renamed from ``get_debug_queries``.

    .. versionchanged:: 3.0
        The info object is a dataclass instead of a tuple.

    .. versionchanged:: 3.0
        The info object attribute ``context`` is renamed to ``location``.

    .. versionchanged:: 3.0
        Not enabled automatically in debug or testing mode.
    """
    return g.get("_sqlalchemy_queries", [])  # type: ignore[no-any-return]


@dataclasses.dataclass
class _QueryInfo:
    """Information about an executed query. Returned by :func:`get_recorded_queries`.

    .. versionchanged:: 3.2
        Added ``bind_key`` and ``parameters_restricted``. Parameters may be restricted
        by policy.

    .. versionchanged:: 3.0
        Renamed from ``_DebugQueryTuple``.

    .. versionchanged:: 3.0
        Changed to a dataclass instead of a tuple.

    .. versionchanged:: 3.0
        ``context`` is renamed to ``location``.
    """

    statement: str | None
    parameters: t.Any
    start_time: float
    end_time: float
    location: str
    bind_key: str | None = None
    parameters_restricted: bool = False

    @property
    def duration(self) -> float:
        return self.end_time - self.start_time


_REDACTED = "***"
_WILDCARD_BIND = "*"
_ParameterPolicy = t.Optional[frozenset[str]]
_listening_engines: weakref.WeakSet[sa.engine.Engine] = weakref.WeakSet()
_app_parameter_policies: weakref.WeakKeyDictionary[
    Flask, dict[str | None, _ParameterPolicy]
] = weakref.WeakKeyDictionary()


def _parse_parameter_policies(
    config: t.Any, bind_keys: t.Iterable[str | None]
) -> dict[str | None, _ParameterPolicy]:
    """Parse :data:`.SQLALCHEMY_RECORD_QUERY_PARAMS` into a policy for each bind.

    ``None`` means all parameter values are recorded. A set of names means only those
    values are recorded. An empty set redacts every value.

    When ``config`` is a dict, its keys are bind keys and ``"*"`` is a fallback. Binds
    with no entry record no parameter values.

    :meta private:

    .. versionadded:: 3.2
    """
    keys = list(bind_keys)

    if not isinstance(config, dict):
        policy = _parse_parameter_rule(config)

        return {key: policy for key in keys}

    for key in config:
        if key is None or isinstance(key, str):
            continue

        raise RuntimeError(
            "'SQLALCHEMY_RECORD_QUERY_PARAMS' bind keys must be strings or None,"
            f" got {type(key).__name__}."
        )

    known = set(keys)
    unknown = [key for key in config if key not in known and key != _WILDCARD_BIND]

    if unknown:
        names = ", ".join("None" if key is None else repr(key) for key in unknown)
        raise RuntimeError(
            "'SQLALCHEMY_RECORD_QUERY_PARAMS' contains bind keys that are not"
            f" configured: {names}."
        )

    fallback = _parse_parameter_rule(config.get(_WILDCARD_BIND, False))
    policies: dict[str | None, _ParameterPolicy] = {}

    for key in keys:
        if key in config:
            policies[key] = _parse_parameter_rule(config[key])
        else:
            policies[key] = fallback

    return policies


def _parse_parameter_rule(value: t.Any) -> _ParameterPolicy:
    if value is None or value is True:
        return None

    if value is False:
        return frozenset()

    if isinstance(value, str):
        return frozenset({value})

    if isinstance(value, (set, frozenset, list, tuple)):
        names = set()

        for name in value:
            if not isinstance(name, str):
                raise RuntimeError(
                    "'SQLALCHEMY_RECORD_QUERY_PARAMS' parameter names must be"
                    f" strings, got {type(name).__name__}."
                )

            names.add(name)

        return frozenset(names)

    raise RuntimeError(
        "'SQLALCHEMY_RECORD_QUERY_PARAMS' must be a bool, a parameter name, a"
        " collection of names, or a dict mapping bind keys to those."
    )


def _listen(engine: sa.engine.Engine, app: Flask, *, bind_key: str | None) -> None:
    """Record queries for an engine on behalf of ``app``. The app is passed to the
    listeners so an extension instance shared by multiple apps keeps each app's
    recorded list separate.

    :meta private:

    .. versionchanged:: 3.2
        Added ``app`` and ``bind_key``.
    """
    if engine in _listening_engines:
        return

    _listening_engines.add(engine)

    # Bind this engine's app and policy with partials. The app checks make a listener
    # installed by one app a no-op for every other app, so two apps sharing one
    # extension instance can keep separate policies.
    start = functools.partial(_record_start, app=app, bind_key=bind_key)
    end = functools.partial(_record_end, app=app, bind_key=bind_key)
    error = functools.partial(_record_error, app=app, bind_key=bind_key)
    sa_event.listen(engine, "before_cursor_execute", start, named=True)
    sa_event.listen(engine, "after_cursor_execute", end, named=True)
    sa_event.listen(engine, "handle_error", error, named=True)


def _record_start(
    context: sa.engine.ExecutionContext,
    app: Flask,
    bind_key: str | None,
    **kwargs: t.Any,
) -> None:
    if (
        not has_app_context() or current_app._get_current_object() is not app  # type: ignore[attr-defined]
    ):
        return

    # Store execution state on the context. An app context can be nested or swapped
    # while a query runs, so the "after" event must not read the policy from the then
    # current app.
    context._fsa_record = (  # type: ignore[attr-defined]
        perf_counter(),
        app,
        bind_key,
        _app_parameter_policies.get(app),
    )


def _record_end(
    context: sa.engine.ExecutionContext,
    app: Flask,
    bind_key: str | None,
    **kwargs: t.Any,
) -> None:
    record = getattr(context, "_fsa_record", None)
    _clear_context(context)

    if record is None or not has_app_context():
        return

    start_time, record_app, bind_key, policies = record

    # Do not put one app's query into another app's list.
    if current_app._get_current_object() is not record_app:  # type: ignore[attr-defined]
        return

    if "_sqlalchemy_queries" not in g:
        g._sqlalchemy_queries = []

    location = _find_location(record_app)
    allowed_parameters = None if policies is None else policies.get(bind_key)

    if allowed_parameters is None:
        parameters = context.parameters
        restricted = False
    else:
        parameters = _restrict_parameters(context, allowed_parameters)
        restricted = True

    g._sqlalchemy_queries.append(
        _QueryInfo(
            statement=context.statement,
            parameters=parameters,
            start_time=start_time,
            end_time=perf_counter(),
            location=location,
            bind_key=bind_key,
            parameters_restricted=restricted,
        )
    )


def _record_error(
    exception_context: sa.engine.ExceptionContext,
    app: Flask,
    bind_key: str | None,
    **kwargs: t.Any,
) -> None:
    """Clear execution state when a query raises. SQLAlchemy doesn't call the "after"
    event in that case, so a failed query is not recorded.
    """
    context = getattr(exception_context, "execution_context", None)

    if context is not None:
        _clear_context(context)


def _clear_context(context: t.Any) -> None:
    try:
        del context._fsa_record
    except AttributeError:
        pass


def _find_location(app: Flask) -> str:
    import_top = app.import_name.partition(".")[0]
    import_dot = f"{import_top}."
    frame = inspect.currentframe()

    while frame:
        name = frame.f_globals.get("__name__")

        if name and (name == import_top or name.startswith(import_dot)):
            code = frame.f_code

            return f"{code.co_filename}:{frame.f_lineno} ({code.co_name})"

        frame = frame.f_back

    return "<unknown>"


def _restrict_parameters(
    context: sa.engine.ExecutionContext, allowed: frozenset[str]
) -> t.Any:
    """Copy parameter values, replacing names that are not allowed with ``"***"``.

    The statement and parameter names stay visible so the shape of the query can still
    be inspected. If names are unavailable, for example when using
    ``exec_driver_sql``, all values are redacted.
    """
    compiled_rows = getattr(context, "compiled_parameters", None)
    names = _original_names(context)

    if isinstance(context.parameters, dict):
        return {
            name: value if _parameter_allowed(name, allowed, names) else _REDACTED
            for name, value in context.parameters.items()
        }

    if (
        isinstance(context.parameters, (list, tuple))
        and isinstance(compiled_rows, list)
        and len(compiled_rows) == len(context.parameters)
        and all(isinstance(row, dict) for row in compiled_rows)
    ):
        return [
            {
                name: value if _parameter_allowed(name, allowed, names) else _REDACTED
                for name, value in row.items()
            }
            for row in compiled_rows
        ]

    if isinstance(context.parameters, (list, tuple)):
        return [tuple(_REDACTED for _ in row) for row in context.parameters]

    return _REDACTED


def _original_names(context: sa.engine.ExecutionContext) -> dict[str, str]:
    """Map the names SQLAlchemy used for the driver to the names in the statement."""
    names: dict[str, str] = {}
    compiled = getattr(context, "compiled", None)

    if compiled is None:
        return names

    for bind, name in getattr(compiled, "bind_names", {}).items():
        if not isinstance(name, str):
            continue

        original = getattr(bind, "_orig_key", None)

        if not isinstance(original, str):
            # Before SQLAlchemy tracked the original key, a "unique" bind's key was
            # rewritten to something like "%(123 id)s".
            key = getattr(bind, "key", None)
            match = re.match(r"%\(.*?\)s (.*)", key) if isinstance(key, str) else None

            if match is not None:
                original = match.group(1)

        if isinstance(original, str):
            names[name] = original

    return names


def _parameter_allowed(
    name: str, allowed: frozenset[str], names: dict[str, str]
) -> bool:
    for candidate in (name, names.get(name)):
        if candidate is None:
            continue

        while True:
            if candidate in allowed:
                return True

            # SQLAlchemy appends suffixes for duplicate or expanded bind names, such
            # as "id_1" or "ids_1_2". Let a policy name match the base name.
            base = re.sub(r"_\d+$", "", candidate)

            if base == candidate:
                break

            candidate = base

    return False
